// ---------------------------------------------------------------------------
// Reference Traits (host-side)
//
// Used ONLY to materialize `GemmKernel::Params` on the host. The Params
// layout for this kernel is invariant of TileShape / Stages / ElementC
// (all those template parameters affect compute / smem layout, not the
// public Params struct fields):
//
//   Params { mode, problem_shape, mainloop {ptr_A**, dA, ptr_B**, dB},
//            epilogue {fusion::Params, ptr_C**, dC, ptr_D**, dD} }
//
// All the field types depend only on (dtype, layout), not on tile/stages.
// The fusion::Params (Sm90LinearCombinationPtrArray) holds alpha/beta and
// per-batch scalar arrays — also tile-invariant.
//
// The NVRTC TU is parameterized via -D macros and may be compiled with a
// different tile/stages/ElementC than the host's reference Traits — Params
// shipped by value through cuLaunchKernel is still ABI-compatible.
// ---------------------------------------------------------------------------

template <bool trans_a, bool trans_b, int SmArch,
          typename Element_ = cutlass::bfloat16_t,
          int TileM = 256, int TileN = 128, int TileK = 64, int Stages = 0>
struct GemmTraits {
  // actlize keys its AIU copy atoms and MMA instruction selection off the
  // ArchTag (cutlass/gemm/config/gemm_operands.hpp compares against
  // arch::PPU0015 and falls back to the PPU0010 variants otherwise), so the tag
  // has to track the device's compute capability. SmArch comes from the runtime
  // dispatch below, mirroring the static path in cutlass_grouped_gemm_ppu.cuh.
  static_assert(SmArch == 80 || SmArch == 89,
                "RTC grouped GEMM supports PPU 1.0 (sm80) and PPU 1.5 (sm89)");
  using ArchTag = std::conditional_t<SmArch == 80, cutlass::arch::PPU0010,
                                     cutlass::arch::PPU0015>;

  using ElementA = Element_;
  using ElementB = Element_;
  using ElementC = Element_;
  using ElementD = Element_;
  using ElementAccumulator = float;

  using LayoutA = std::conditional_t<trans_a, cutlass::layout::ColumnMajor,
                                     cutlass::layout::RowMajor>;
  using LayoutB = std::conditional_t<trans_b, cutlass::layout::ColumnMajor,
                                     cutlass::layout::RowMajor>;
  using LayoutC = cutlass::layout::RowMajor;

  static constexpr int kAlignmentA = 8;
  static constexpr int kAlignmentB = 8;
  static constexpr int kAlignmentC = 8;
  static constexpr int kAlignmentD = 8;

  // Tile MUST match the NVRTC cubin's tile: the GroupScheduler bakes
  // FastDivmod(cta_shape) into Params at to_underlying_arguments time, and the
  // host derives block size and grid from it too. A fixed host tile with a
  // differently-compiled cubin desynchronizes the tile math.
  using TileShape = cute::Shape<cute::Int<TileM>, cute::Int<TileN>, cute::Int<TileK>>;
  using ClusterShape = cute::Shape<cute::_64, cute::_64, cute::_64>;

  using KernelSchedule = cutlass::gemm::KernelPtrArrayTmaWarpSpecializedCooperative;
  using EpilogueSchedule = cutlass::epilogue::EpiloguePtrArraySimtVectorized;

  using ProblemShape =
      cutlass::gemm::GroupProblemShape<cute::Shape<int, int, int>>;
  using ProblemShapeType = typename ProblemShape::UnderlyingProblemShape;

  using CollectiveEpilogue = typename cutlass::epilogue::collective::CollectiveBuilder<
      ArchTag, cutlass::arch::OpClassTensorOp,
      TileShape, ClusterShape,
      cutlass::epilogue::collective::EpilogueTileAuto,
      ElementAccumulator, ElementAccumulator,
      ElementC, LayoutC*, kAlignmentC,
      ElementD, LayoutC*, kAlignmentD,
      EpilogueSchedule,
      cutlass::epilogue::fusion::LinearCombination<ElementD, ElementAccumulator>>::CollectiveOp;

  // Stage policy must match the NVRTC kernel's NVTE_GG_STAGES branch so the
  // Params layout stays ABI-identical: 0 -> auto-carveout, else StageCount<N>.
  using StageCountPolicy = std::conditional_t<
      Stages == 0,
      cutlass::gemm::collective::StageCountAutoCarveout<
          static_cast<int>(sizeof(typename CollectiveEpilogue::SharedStorage))>,
      cutlass::gemm::collective::StageCount<Stages>>;

  using CollectiveMainloop = typename cutlass::gemm::collective::CollectiveBuilder<
      ArchTag, cutlass::arch::OpClassTensorOp,
      ElementA, LayoutA*, kAlignmentA,
      ElementB, LayoutB*, kAlignmentB,
      ElementAccumulator,
      TileShape, ClusterShape,
      StageCountPolicy,
      KernelSchedule>::CollectiveOp;

  using GemmKernel = cutlass::gemm::kernel::GemmUniversal<
      ProblemShape, CollectiveMainloop, CollectiveEpilogue>;

  using StrideA = typename CollectiveMainloop::StrideA;
  using StrideB = typename CollectiveMainloop::StrideB;
  using StrideC = typename CollectiveEpilogue::StrideC;
  using StrideD = typename CollectiveEpilogue::StrideD;
};

// ---------------------------------------------------------------------------
// Tile / stages / with_C config
// ---------------------------------------------------------------------------

struct TileConfig {
  int tile_m = 256;
  int tile_n = 128;
  int tile_k = 64;
  int stages = 0;     // 0 = StageCountAutoCarveout
  bool with_C = false;
  // Production launch policy associated with a tuned tile. Zero keeps the
  // architecture-independent occupancy/default grid path.
  int workers_per_cu = 0;

  bool operator==(TileConfig const& o) const {
    return tile_m == o.tile_m && tile_n == o.tile_n && tile_k == o.tile_k &&
           stages == o.stages && with_C == o.with_C;
  }
};

constexpr TileConfig kDefaultTile{256, 256, 64, 3, false};

// PPU-side feasibility check. Pessimistic — we'd rather reject a valid tile
// and fall back than try to compile something that fails after a 25 s NVRTC
// run. The ranges are derived from PPU __HGGCCC__ usage in
// cutlass_grouped_gemm.cuh and from MainloopAcomputeAiuBatchArray's smem
// budget on PPU SM80 (~192 KB dynamic).
bool is_valid_ppu_tile(TileConfig const& cfg) {
  // Sanity bounds.
  if (cfg.tile_m < 32 || cfg.tile_n < 32 || cfg.tile_k < 32) return false;
  if (cfg.tile_m > 256 || cfg.tile_n > 256) return false;
  if (cfg.tile_k > 128) return false;
  if (cfg.tile_m % 16 || cfg.tile_n % 16 || cfg.tile_k % 16) return false;
  if (cfg.stages < 0 || cfg.stages > 8) return false;

  // Smem budget. The kernel layer aliases mainloop and epilogue storage in a
  // union, so the launch needs the larger footprint rather than their sum.
  int stages = cfg.stages == 0 ? 3 : cfg.stages;
  size_t mainloop_bytes =
      (static_cast<size_t>(cfg.tile_m) + cfg.tile_n) * cfg.tile_k * 2 * stages;
  size_t epi_bytes =
      static_cast<size_t>(cfg.tile_m / 64) * 16 * cfg.tile_n * 4 + 16;
  if (std::max(mainloop_bytes, epi_bytes) > (256 * 1024)) return false;

  return true;
}

// Tiles with host-compiled GemmTraits/launcher instantiations
// (see the dispatch table in dispatch()). Any other tile is snapped to the
// default, so the heuristic prefers a tile from this set when cuBLAS offers
// several — otherwise a good-but-unsupported recommendation is wasted.
inline bool is_supported_rtc_tile(int m, int n, int k) {
  return k == 64 && ((m == 256 && n == 256) || (m == 256 && n == 128) ||
                     (m == 128 && n == 256) || (m == 128 && n == 128) ||
                     (m == 256 && n == 64) || (m == 128 && n == 64));
}

// Every (tile, stages) pair the host instantiates a launcher for. This list is
// the single source of truth: the snap predicate in dispatch() and the dispatch
// table itself both expand it, so the two cannot drift apart (a cfg that passed
// the predicate but had no table entry used to fall off the end of the table
// and silently skip the GEMM).
//
// stages 0 = StageCountAutoCarveout. Explicit counts matter because mainloop
// smem = (BM+BN)*BK*2B*stages sets the pipeline depth; is_valid_ppu_tile caps
// that at 256 KB, which the device accepts as dynamic smem (256x256x64 at
// 4 stages and 256x256x128 at 2 stages both use the full 256 KB budget).
//
// The second block is the exploration set for tile tuning beyond the BK=64
// menu: a shallower BK buys pipeline depth at equal smem, a deeper BK cuts the
// k-step count, and 128x256 is the mirror of 256x128 for the layouts where N is
// the short extent. The adaptive selector never returns these — reach them with
// NVTE_GG_FORCE_TILE.
#define NVTE_GG_TILE_TABLE(F)                                                  \
  F(256, 256, 64, 0) F(256, 128, 64, 0) F(128, 128, 64, 0)                     \
  F(256, 64, 64, 0) F(128, 64, 64, 0)                                          \
  F(256, 128, 64, 2) F(256, 128, 64, 3) F(256, 128, 64, 4)                     \
  F(256, 256, 64, 2) F(256, 256, 64, 3) F(256, 256, 64, 4)                     \
  F(256, 256, 32, 0) F(256, 256, 32, 4) F(256, 256, 32, 6)                     \
  F(256, 256, 32, 8) F(256, 256, 128, 2) F(256, 128, 128, 2)                   \
  F(128, 256, 64, 0) F(128, 256, 64, 2) F(128, 256, 64, 3)                     \
  F(128, 256, 64, 4) F(128, 128, 64, 4) F(128, 128, 32, 3)                     \
  F(128, 256, 128, 2) F(128, 128, 128, 2) F(128, 128, 64, 2)                   \
  F(256, 128, 32, 4)

inline bool has_host_instantiation(TileConfig const& cfg) {
#define NVTE_GG_TILE_MATCH(TM, TN, TK, ST)                                     \
  if (cfg.tile_m == (TM) && cfg.tile_n == (TN) && cfg.tile_k == (TK) &&        \
      cfg.stages == (ST)) {                                                    \
    return true;                                                               \
  }
  NVTE_GG_TILE_TABLE(NVTE_GG_TILE_MATCH)
#undef NVTE_GG_TILE_MATCH
  return false;
}

