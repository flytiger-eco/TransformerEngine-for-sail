bool lookup_tuned_tile(int avg_m, int avg_n, int avg_k, bool trans_a,
                       bool trans_b, int sm_arch, bool with_C,
                       TileConfig* cfg) {
  // Route toggles are parsed once per process: getenv<bool> constructs an
  // istringstream on every call, and this lookup runs on every grouped-GEMM
  // launch.
  static const bool no_tuned =
      getenv<bool>("NVTE_GG_NO_TUNED_TILE_OVERRIDES", false);
  if (no_tuned) return false;
  for (auto const& entry : kTunedTileEntries) {
    if (avg_m < entry.m_lo || avg_m > entry.m_hi ||
        avg_n < entry.n_lo || avg_n > entry.n_hi ||
        avg_k < entry.k_lo || avg_k > entry.k_hi ||
        entry.trans_a != trans_a || entry.trans_b != trans_b ||
        entry.sm_arch != sm_arch) {
      continue;
    }
    // Preserve the existing NN BK=128 opt-out for comparison and debugging.
    if (!trans_a && !trans_b && entry.tile_k == 128) {
      static const bool no_nn_bk128 = getenv<bool>("NVTE_GG_NO_NN_BK128", false);
      if (no_nn_bk128) {
        return false;
      }
    }
    *cfg = TileConfig{entry.tile_m, entry.tile_n, entry.tile_k, entry.stages,
                      with_C, entry.workers_per_cu};
    return true;
  }
  return false;
}

TileConfig get_or_query_tile_stages(int avg_m, int avg_n, int avg_k,
                                    int num_groups, bool trans_a, bool trans_b,
                                    int sm_arch, int num_sms, bool with_C) {
  // Manual override for validation: NVTE_GG_FORCE_TILE="M,N,K" forces the tile
  // regardless of the heuristic, so the same problem can be driven through
  // different RTC tiles to confirm the tile is honored. An optional 4th field
  // forces the stage count ("M,N,K,S"); 0 keeps auto-carveout, and 2..4 are the
  // counts the dispatch table instantiates for 256x128 and 256x256. Stages
  // matter because they set the mainloop smem, which is what decides whether a
  // second CTA fits on a CU: 256x128 at 4 stages needs 192 KB and caps
  // residency at 1, while the same tile at 2 stages needs 96 KB and lets 2 CTAs
  // co-reside. An out-of-range count is snapped back to auto rather than
  // launching nothing.
  // Parsed once per process: this selector runs on every grouped-GEMM launch
  // and the getenv calls (istringstream-backed bools especially) cost a few
  // microseconds of host time each launch.
  static const std::string force_tile_env = getenv<std::string>("NVTE_GG_FORCE_TILE");
  if (!force_tile_env.empty()) {
    int fm = 0, fn = 0, fk = 0, fs = 0;
    const int got = std::sscanf(force_tile_env.c_str(), "%d,%d,%d,%d", &fm, &fn, &fk, &fs);
    if (got == 3 || got == 4) {
      TileConfig forced{fm, fn, fk, got == 4 ? fs : 0, with_C};
      if (verbose_tile_debug()) {
        NVTE_WARN("[GG-DEBUG] NVTE_GG_FORCE_TILE override -> tile=(", fm, ",",
                  fn, ",", fk, ") stages=", forced.stages);
      }
      return forced;
    }
    NVTE_WARN("NVTE_GG_FORCE_TILE='", force_tile_env,
              "' is malformed; expected \"M,N,K\" or \"M,N,K,stages\". "
              "Ignoring.");
  }

  TileConfig cfg;
  const bool verbose = verbose_tile_debug();
  // Tuned ranges are stable routing decisions. Match them before consulting
  // the exact-shape heuristic cache so training-time N/K fluctuations neither
  // miss the tuned tile nor create one cache entry per observed average.
  if (lookup_tuned_tile(avg_m, avg_n, avg_k, trans_a, trans_b, sm_arch,
                        with_C, &cfg)) {
    if (verbose) {
      NVTE_WARN("tuned tile override picked tile=(", cfg.tile_m, ",",
                cfg.tile_n, ",", cfg.tile_k, ") stages=", cfg.stages,
                " for groups=", num_groups, " shape (M=", avg_m, ",N=",
                avg_n, ",K=", avg_k, ").");
    }
    return cfg;
  }

  static const bool no_tuned_key =
      getenv<bool>("NVTE_GG_NO_TUNED_TILE_OVERRIDES", false);
  static const bool use_cublas_heuristic =
      getenv<bool>("NVTE_GG_USE_CUBLAS_HEURISTIC", false);
  static const bool no_nn_bk128_key = getenv<bool>("NVTE_GG_NO_NN_BK128", false);
  HeuristicKey key{
      avg_m, avg_n, avg_k, num_groups, trans_a, trans_b, sm_arch,
      no_tuned_key, use_cublas_heuristic, no_nn_bk128_key};
  {
    std::lock_guard<std::mutex> lk(heuristic_mutex());
    auto it = heuristic_cache().find(key);
    if (it != heuristic_cache().end()) {
      TileConfig cached = it->second;
      cached.with_C = with_C;
      return cached;
    }
  }
  // Try cublasLtMatmulAlgoGetHeuristic when requested. On PPU's cublasLt the
  // top algo doesn't expose tile/stages config attributes (returns _UNDEFINED),
  // so the default selector is the DeepGemm-ported adaptive model below.
  if (use_cublas_heuristic) {
    cfg = query_optimal_tile_stages(avg_m, avg_n, avg_k, trans_a, trans_b);
    if (cfg == kDefaultTile && verbose) {
      NVTE_WARN("cuBLAS heuristic gave no usable tile; using default tile=(",
                cfg.tile_m, ",", cfg.tile_n, ",", cfg.tile_k, ") stages=",
                cfg.stages, " for shape (M=", avg_m, ",N=", avg_n, ",K=",
                avg_k, ").");
    }
  } else {
    // Adaptive selector (ppu_adaptive_tile.hpp). It scores the tiles RTC has
    // cubins for with the dense selector's makespan model, so it needs the
    // whole grid: num_groups (this is one persistent kernel over every group,
    // not one launch per group) and whether LayoutB is RowMajor, which decides
    // whether BN is the B tile's contiguous load width. The stage count then
    // comes from preferred_stages(), which overrides auto-carveout where it was
    // measured to under-provision the mainloop.
    int cus = num_sms > 0 ? num_sms : 39;
    // launch_grouped_gemm_rtc swaps the operands (tb = trans_a), so LayoutB is
    // ColumnMajor exactly when trans_a is set -- see rtc/cutlass_grouped_gemm.cu
    // NVTE_GG_TRANS_B.
    const bool layout_b_row_major = !trans_a;
    ppu_adaptive_tile::RtcTile t = ppu_adaptive_tile::choose_rtc_tile(
        avg_m, avg_n, avg_k, cus, num_groups, layout_b_row_major);
    cfg = TileConfig{t.bm, t.bn, t.bk, preferred_stages(t.bm, t.bn, t.bk),
                     with_C};
    // NN dgrad (trans_a=trans_b=false) benefits from a deeper BK. Its GEMM
    // reduction extent K is the FFN hidden width n (always >=512), so BK=128
    // halves the k-step count and, at 2 stages, fits the same 256 KB smem as
    // 256x256x64 s4. Measured -4 to -7% on 256x256 across both the deep-M
    // (2048 tokens/expert) and shallow-M (mpe<=256) regimes, monotone in every
    // one of 42 cases (profile/gg_z16_m2048/tune_bk*.py). This is layout-
    // specific: TN's B-operand path is slower at BK=128 (+10%), and NT's K is
    // the per-expert token count mpe which can drop below 128 and waste masked
    // k-loads -- both keep BK=64. Opt out with NVTE_GG_NO_NN_BK128=1.
    if (t.bm == 256 && t.bn == 256 && !trans_a && !trans_b &&
        !no_nn_bk128_key) {
      cfg.tile_k = 128;
      cfg.stages = 2;
    }
    if (!is_valid_ppu_tile(cfg)) cfg = kDefaultTile;
    if (verbose) {
      NVTE_WARN("adaptive tile heuristic (num_sms=", cus, " groups=", num_groups,
                " LayoutB=", (layout_b_row_major ? "RowMajor" : "ColumnMajor"),
                ") picked tile=(", cfg.tile_m, ",", cfg.tile_n, ",", cfg.tile_k,
                ") stages=", cfg.stages, " for shape (M=", avg_m, ",N=", avg_n,
                ",K=", avg_k, ").");
    }
  }
  cfg.with_C = with_C;
  {
    std::lock_guard<std::mutex> lk(heuristic_mutex());
    heuristic_cache()[key] = cfg;
  }
  return cfg;
}

