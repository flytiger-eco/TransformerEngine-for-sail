// Host TU for NVRTC-JIT grouped GEMM on PPU SM80/SM89.
//
// Pipeline:
//   1. dispatch()
//      - compute avg (M, N, K) across groups for the cuBLAS heuristic
//      - query cublasLtMatmulAlgoGetHeuristic for the equivalent single-GEMM
//        problem to pick (TileM, TileN, TileK, Stages); cached per
//        (avg_m, avg_n, avg_k, transa, transb, sm) so we only pay the
//        heuristic cost once per unique shape
//      - validate tile is implementable on PPU (smem fits, dims sane); fall
//        back to the fixed (256, 256, 64), stages=3 configuration on mismatch
//      - select ElementC=void variant when accumulate=false
//   2. launch_grouped_gemm_rtc()
//      - pack host-side per-group ptr arrays for A/B/C/D
//      - construct GemmKernel::Arguments and call to_underlying_arguments
//        on the host (Params layout is invariant of tile/stages/ElementC,
//        so a single "reference" Traits is fine for ABI)
//      - mirror GemmUniversalAdapter::run: smem attribute, grid/block from
//        the kernel's static helpers, cuLaunchKernel with Params by value
//   3. compile_kernel()
//      - inject -DNVTE_GG_TILE_M/_N/_K/_STAGES/_WITH_C macros
//      - SM-arch specific NVRTC flags: sm_80a for SM80, sm_89 for SM89
//        (matches the static cutlass_grouped_gemm_ppu.cu compile options in
//        CMakeLists.txt). The PPU generation is selected purely by the
//        ArchTag (PPU0010 / PPU0015), not by a preprocessor version macro.
//      - cubin symbol encodes the full config so each (layout, sm, tile,
//        stages, with_C) compiles to a distinct symbol visible to profilers

