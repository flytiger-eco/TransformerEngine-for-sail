  if constexpr (std::is_same_v<T, cutlass::bfloat16_t>) return "bf16";
  else if constexpr (std::is_same_v<T, cutlass::half_t>) return "fp16";
  else if constexpr (std::is_same_v<T, float>) return "fp32";
  else return "x";
}

template <typename L>
inline const char* layout_short() {
  if constexpr (std::is_same_v<L, cutlass::layout::RowMajor>) return "RM";
  else if constexpr (std::is_same_v<L, cutlass::layout::ColumnMajor>) return "CM";
  else return "X";
}

template <typename T>
inline const char* element_name() {
  if constexpr (std::is_same_v<T, cutlass::bfloat16_t>) return "bfloat16_t";
  else if constexpr (std::is_same_v<T, cutlass::half_t>) return "half_t";
  else if constexpr (std::is_same_v<T, float>) return "float";
  else return "?";
}

template <typename L>
inline const char* layout_name() {
  if constexpr (std::is_same_v<L, cutlass::layout::RowMajor>) return "RowMajor";
  else if constexpr (std::is_same_v<L, cutlass::layout::ColumnMajor>) return "ColumnMajor";
  else return "?";
}

