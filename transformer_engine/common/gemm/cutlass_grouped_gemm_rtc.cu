namespace {

// Filesystem cache for compiled RTC cubins. hgrtc's own on-disk cache is
// disabled with --no-cache, so TE manages a cache keyed by the full compile
// input (see get_or_compile()). The cache directory can be overridden with
// NVTE_GG_RTC_CACHE_DIR; it defaults to $XDG_CACHE_HOME/nvte_gg_rtc or
// $HOME/.cache/nvte_gg_rtc.
std::filesystem::path get_rtc_cache_dir() {
  namespace fs = std::filesystem;
  if (auto dir = getenv<std::string>("NVTE_GG_RTC_CACHE_DIR"); !dir.empty()) {
    return fs::path(dir);
  }
  if (auto cache_home = getenv<std::string>("XDG_CACHE_HOME"); !cache_home.empty()) {
    return fs::path(cache_home) / "nvte_gg_rtc";
  }
  if (auto home = getenv<std::string>("HOME"); !home.empty()) {
    return fs::path(home) / ".cache" / "nvte_gg_rtc";
  }
  return {};
}

std::string cache_key_digest(const std::string& key) {
  const uint64_t h0 = fnv1a_64(key.data(), key.size(), 0xcbf29ce484222325ull);
  const uint64_t h1 = fnv1a_64(key.data(), key.size(), 0x9e3779b97f4a7c15ull);
  return digest_to_hex(h0, h1);
}

std::filesystem::path get_rtc_cache_path(const std::string& cache_key) {
  const auto dir = get_rtc_cache_dir();
  if (dir.empty()) return {};
  return dir / (cache_key_digest(cache_key) + ".cubin");
}

std::optional<CompiledKernel> try_load_cached_cubin(
    const std::string& cache_key, const std::string& kernel_symbol) {
  namespace fs = std::filesystem;
  const auto path = get_rtc_cache_path(cache_key);
  if (path.empty() || !fs::exists(path)) return std::nullopt;

  std::ifstream f(path, std::ios::binary);
  if (!f) return std::nullopt;
  const std::string cubin{std::istreambuf_iterator<char>(f),
                          std::istreambuf_iterator<char>()};
  if (cubin.empty()) return std::nullopt;

  if (getenv<bool>("NVTE_CUTLASS_GROUPED_GEMM_RTC_VERBOSE", false)) {
    NVTE_WARN("CUTLASS RTC grouped GEMM: loaded cached cubin ", path.string(),
              " (", cubin.size(), " B) for ", kernel_symbol, ".");
  }
  return load_cubin_module(cubin, kernel_symbol);
}

void save_cached_cubin(const std::string& cache_key, const std::string& cubin) {
  namespace fs = std::filesystem;
  const auto path = get_rtc_cache_path(cache_key);
  if (path.empty()) return;

  std::error_code ec;
  fs::create_directories(path.parent_path(), ec);
  if (ec) return;

  const auto tmp = path.string() + ".tmp";
  {
    std::ofstream f(tmp, std::ios::binary);
    if (!f) return;
    f.write(cubin.data(), cubin.size());
    if (!f) return;
  }
  fs::rename(tmp, path, ec);
  if (ec) {
    fs::remove(tmp, ec);
  }
}

