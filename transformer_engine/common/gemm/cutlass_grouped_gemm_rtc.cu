namespace {

// Cache key for heuristic results. Layouts collapse to (transa, transb).
// num_groups is part of the key because the adaptive selector prices the wave
// count over all groups, so the same average shape can want a different tile
// at a different expert count (e.g. (256,1536,4096) TN takes 256x128 at 16
// experts but 256x256 at 32).
struct HeuristicKey {
  int avg_m, avg_n, avg_k;
  int num_groups;
  bool trans_a, trans_b;
  int sm_arch;
  bool tuned_overrides_disabled;
  bool use_cublas_heuristic;
  bool nn_bk128_disabled;
  bool operator<(HeuristicKey const& o) const {
    return std::tie(avg_m, avg_n, avg_k, num_groups, trans_a, trans_b, sm_arch,
                    tuned_overrides_disabled, use_cublas_heuristic,
                    nn_bk128_disabled) <
           std::tie(o.avg_m, o.avg_n, o.avg_k, o.num_groups, o.trans_a, o.trans_b,
                    o.sm_arch, o.tuned_overrides_disabled,
                    o.use_cublas_heuristic, o.nn_bk128_disabled);
  }
};

std::mutex& heuristic_mutex() {
  static std::mutex m;
  return m;
}

std::map<HeuristicKey, TileConfig>& heuristic_cache() {
  static std::map<HeuristicKey, TileConfig> c;
  return c;
}

// Decode CUBLASLT_ALGO_CONFIG_TILE_ID enum -> (tile_M, tile_N).
// Only covers the subset of tiles that overlap with PPU's supported range
// (M, N in [32, 256], multiples of 16). Other enums are not mapped and the
// caller treats that as "tile unknown" and falls back.
bool decode_cublas_tile_id(uint32_t tile_id, int* tm, int* tn) {
  switch (static_cast<cublasLtMatmulTile_t>(tile_id)) {
    case CUBLASLT_MATMUL_TILE_32x32:   *tm = 32;  *tn = 32;  return true;
    case CUBLASLT_MATMUL_TILE_32x64:   *tm = 32;  *tn = 64;  return true;
    case CUBLASLT_MATMUL_TILE_64x32:   *tm = 64;  *tn = 32;  return true;
    case CUBLASLT_MATMUL_TILE_32x128:  *tm = 32;  *tn = 128; return true;
    case CUBLASLT_MATMUL_TILE_64x64:   *tm = 64;  *tn = 64;  return true;
    case CUBLASLT_MATMUL_TILE_128x32:  *tm = 128; *tn = 32;  return true;
    case CUBLASLT_MATMUL_TILE_64x128:  *tm = 64;  *tn = 128; return true;
    case CUBLASLT_MATMUL_TILE_128x64:  *tm = 128; *tn = 64;  return true;
    case CUBLASLT_MATMUL_TILE_64x256:  *tm = 64;  *tn = 256; return true;
    case CUBLASLT_MATMUL_TILE_128x128: *tm = 128; *tn = 128; return true;
    case CUBLASLT_MATMUL_TILE_256x64:  *tm = 256; *tn = 64;  return true;
    case CUBLASLT_MATMUL_TILE_128x256: *tm = 128; *tn = 256; return true;
    case CUBLASLT_MATMUL_TILE_256x128: *tm = 256; *tn = 128; return true;
    case CUBLASLT_MATMUL_TILE_32x256:  *tm = 32;  *tn = 256; return true;
    case CUBLASLT_MATMUL_TILE_256x32:  *tm = 256; *tn = 32;  return true;
    case CUBLASLT_MATMUL_TILE_96x64:   *tm = 96;  *tn = 64;  return true;
    case CUBLASLT_MATMUL_TILE_64x96:   *tm = 64;  *tn = 96;  return true;
    default: return false;
  }
}

// Decode CUBLASLT_ALGO_CONFIG_STAGES_ID enum -> (tile_K, stages).
// cuBLAS stages enum encodes "KxN" => K is the K-tile dim, N is the stage
// count. Only covers the K values PPU's MainloopAcomputeAiuBatchArray can
// reasonably pipeline (32, 64, 128).
bool decode_cublas_stages_id(uint32_t stages_id, int* tk, int* nstages) {
  switch (static_cast<cublasLtMatmulStages_t>(stages_id)) {
    case CUBLASLT_MATMUL_STAGES_32x1: *tk = 32;  *nstages = 1; return true;
    case CUBLASLT_MATMUL_STAGES_32x2: *tk = 32;  *nstages = 2; return true;
    case CUBLASLT_MATMUL_STAGES_32x3: *tk = 32;  *nstages = 3; return true;
    case CUBLASLT_MATMUL_STAGES_32x4: *tk = 32;  *nstages = 4; return true;
    case CUBLASLT_MATMUL_STAGES_32x5: *tk = 32;  *nstages = 5; return true;
    case CUBLASLT_MATMUL_STAGES_32x6: *tk = 32;  *nstages = 6; return true;
    case CUBLASLT_MATMUL_STAGES_64x1: *tk = 64;  *nstages = 1; return true;
    case CUBLASLT_MATMUL_STAGES_64x2: *tk = 64;  *nstages = 2; return true;
    case CUBLASLT_MATMUL_STAGES_64x3: *tk = 64;  *nstages = 3; return true;
    case CUBLASLT_MATMUL_STAGES_64x4: *tk = 64;  *nstages = 4; return true;
    case CUBLASLT_MATMUL_STAGES_64x5: *tk = 64;  *nstages = 5; return true;
    case CUBLASLT_MATMUL_STAGES_64x6: *tk = 64;  *nstages = 6; return true;
    case CUBLASLT_MATMUL_STAGES_128x1: *tk = 128; *nstages = 1; return true;
    default: return false;
  }
}

// Run cublasLtMatmulAlgoGetHeuristic on a single bf16 GEMM with shape
// (M, N, K) and the given trans flags, then peel out the recommended
// (tile_M, tile_N, tile_K, stages). Returns kDefaultTile on any failure.
TileConfig query_optimal_tile_stages(int m, int n, int k, bool trans_a,
                                     bool trans_b) {
  TileConfig out = kDefaultTile;

  cublasLtHandle_t handle = nullptr;
  try {
    handle = CublasLtHandleForRtc::Instance().GetHandle();
  } catch (...) {
    return kDefaultTile;
  }

  cublasOperation_t opa = trans_a ? CUBLAS_OP_T : CUBLAS_OP_N;
  cublasOperation_t opb = trans_b ? CUBLAS_OP_T : CUBLAS_OP_N;

  cublasLtMatmulDesc_t op_desc = nullptr;
  cublasLtMatrixLayout_t a_desc = nullptr, b_desc = nullptr,
                          c_desc = nullptr, d_desc = nullptr;
  cublasLtMatmulPreference_t pref = nullptr;

  auto cleanup = [&]() {
    if (pref) cublasLtMatmulPreferenceDestroy(pref);
    if (a_desc) cublasLtMatrixLayoutDestroy(a_desc);
    if (b_desc) cublasLtMatrixLayoutDestroy(b_desc);
    if (c_desc) cublasLtMatrixLayoutDestroy(c_desc);
    if (d_desc) cublasLtMatrixLayoutDestroy(d_desc);
    if (op_desc) cublasLtMatmulDescDestroy(op_desc);
  };

  // bf16 GEMM with FP32 accumulate — same compute as the actual workload.
  auto status = cublasLtMatmulDescCreate(&op_desc, CUBLAS_COMPUTE_32F,
                                         CUDA_R_32F);
  if (status != CUBLAS_STATUS_SUCCESS) { cleanup(); return kDefaultTile; }

  cublasLtMatmulDescSetAttribute(op_desc, CUBLASLT_MATMUL_DESC_TRANSA, &opa,
                                 sizeof(opa));
  cublasLtMatmulDescSetAttribute(op_desc, CUBLASLT_MATMUL_DESC_TRANSB, &opb,
                                 sizeof(opb));

  // A: M x K (or K x M when transposed); B: K x N (or N x K when transposed).
  // Strides set to packed col-major (cuBLAS native).
  int64_t lda = (opa == CUBLAS_OP_N) ? m : k;
  int64_t ldb = (opb == CUBLAS_OP_N) ? k : n;
  int64_t ldc = m;
  cublasLtMatrixLayoutCreate(&a_desc, CUDA_R_16BF,
                              opa == CUBLAS_OP_N ? m : k,
                              opa == CUBLAS_OP_N ? k : m, lda);
  cublasLtMatrixLayoutCreate(&b_desc, CUDA_R_16BF,
                              opb == CUBLAS_OP_N ? k : n,
                              opb == CUBLAS_OP_N ? n : k, ldb);
  cublasLtMatrixLayoutCreate(&c_desc, CUDA_R_16BF, m, n, ldc);
  cublasLtMatrixLayoutCreate(&d_desc, CUDA_R_16BF, m, n, ldc);

  cublasLtMatmulPreferenceCreate(&pref);
  // The standalone probe that DOES get valid tile IDs on PPU offers 32 MB and
  // asks for several algos. PPU's cuBLAS shim appears to gate tuned kernels
  // (the ones that expose TILE_ID / STAGES_ID) behind a large workspace and to
  // return a generic tile-less algo as result[0]. Mirror the probe and make
  // both knobs tunable so 810E can bisect the real cause.
  size_t ws_mb = 32;
  if (auto e = getenv<std::string>("NVTE_GG_HEURISTIC_WS_MB"); !e.empty()) {
    ws_mb = static_cast<size_t>(std::max(1, std::atoi(e.c_str())));
  }
  size_t workspace_bytes = ws_mb * 1024 * 1024;
  cublasLtMatmulPreferenceSetAttribute(
      pref, CUBLASLT_MATMUL_PREF_MAX_WORKSPACE_BYTES, &workspace_bytes,
      sizeof(workspace_bytes));

  int req_algos = 8;
  if (auto e = getenv<std::string>("NVTE_GG_HEURISTIC_ALGOS"); !e.empty()) {
    req_algos = std::min(32, std::max(1, std::atoi(e.c_str())));
  }
  std::vector<cublasLtMatmulHeuristicResult_t> results(req_algos);
  int returned = 0;
  status = cublasLtMatmulAlgoGetHeuristic(handle, op_desc, a_desc, b_desc,
                                          c_desc, d_desc, pref, req_algos,
                                          results.data(), &returned);
  const bool verbose =
      getenv<bool>("NVTE_CUTLASS_GROUPED_GEMM_RTC_VERBOSE", false);
  if (status != CUBLAS_STATUS_SUCCESS || returned == 0) {
    if (verbose) {
      NVTE_WARN("cuBLAS GetHeuristic (M=", m, ",N=", n, ",K=", k, ",ta=",
                trans_a, ",tb=", trans_b, ",ws=", ws_mb, "MB,req=", req_algos,
                "): status=", static_cast<int>(status), " returned=", returned);
    }
    cleanup();
    return kDefaultTile;
  }

  if (verbose) {
    NVTE_WARN("cuBLAS GetHeuristic (M=", m, ",N=", n, ",K=", k, ",ta=", trans_a,
              ",tb=", trans_b, ",ws=", ws_mb, "MB,req=", req_algos,
              "): returned=", returned);
  }

  // Prefer the first candidate whose tile is directly supported by the host
  // dispatch table; fall back to the first merely-valid tile (which will be
  // snapped to the default downstream) only if none is supported.
  int tm = 0, tn = 0, tk = 0;
  bool have_supported = false, have_valid = false;
  int vm = 0, vn = 0, vk = 0;
  for (int i = 0; i < returned; ++i) {
    int32_t algo_id = -1;
    uint32_t tile_id = 0, stages_id = 0, split_k = 0, custom = 0;
    size_t written = 0;
    cublasLtMatmulAlgoConfigGetAttribute(&results[i].algo,
                                         CUBLASLT_ALGO_CONFIG_ID, &algo_id,
                                         sizeof(algo_id), &written);
    cublasStatus_t s_tile = cublasLtMatmulAlgoConfigGetAttribute(
        &results[i].algo, CUBLASLT_ALGO_CONFIG_TILE_ID, &tile_id,
        sizeof(tile_id), &written);
    cublasStatus_t s_stg = cublasLtMatmulAlgoConfigGetAttribute(
        &results[i].algo, CUBLASLT_ALGO_CONFIG_STAGES_ID, &stages_id,
        sizeof(stages_id), &written);
    cublasLtMatmulAlgoConfigGetAttribute(&results[i].algo,
                                         CUBLASLT_ALGO_CONFIG_SPLITK_NUM,
                                         &split_k, sizeof(split_k), &written);
    cublasLtMatmulAlgoConfigGetAttribute(&results[i].algo,
                                         CUBLASLT_ALGO_CONFIG_CUSTOM_OPTION,
                                         &custom, sizeof(custom), &written);

    int cand_tm = 0, cand_tn = 0, cand_tk = 0, cand_ns = 0;
    bool cand_ok_tile = (s_tile == CUBLAS_STATUS_SUCCESS) &&
                        decode_cublas_tile_id(tile_id, &cand_tm, &cand_tn);
    bool cand_ok_stages = (s_stg == CUBLAS_STATUS_SUCCESS) &&
                          decode_cublas_stages_id(stages_id, &cand_tk, &cand_ns);
    bool cand_valid = cand_ok_tile && cand_ok_stages;
    bool cand_supported =
        cand_valid && is_supported_rtc_tile(cand_tm, cand_tn, cand_tk);

    if (verbose) {
      NVTE_WARN("  result[", i, "/", returned, "]: state=",
                static_cast<int>(results[i].state), " algo_id=", algo_id,
                " tile_id=", tile_id, " stages_id=", stages_id,
                " splitK=", split_k, " custom=", custom,
                " ws=", results[i].workspaceSize, " waves=", results[i].wavesCount,
                " -> decoded_tile=(", cand_tm, ",", cand_tn, ",", cand_tk,
                ") stages=", cand_ns, " ok_tile=", cand_ok_tile,
                " ok_stages=", cand_ok_stages, " supported=", cand_supported);
    }

    if (cand_valid && !have_valid) {
      vm = cand_tm; vn = cand_tn; vk = cand_tk;
      have_valid = true;
    }
    if (cand_supported && !have_supported) {
      tm = cand_tm; tn = cand_tn; tk = cand_tk;
      have_supported = true;
      if (!verbose) break;  // best possible outcome; stop early
    }
  }
  cleanup();

  if (have_supported || have_valid) {
    // Borrow only cuBLAS's tile M/N/K. cuBLAS's STAGES_ID refers to its own
    // kernel catalog and does not map onto the CUTLASS pipeline stage count;
    // force auto-carveout (stages=0), which is validated and fastest on PPU.
    const int rm = have_supported ? tm : vm;
    const int rn = have_supported ? tn : vn;
    const int rk = have_supported ? tk : vk;
    TileConfig cand{rm, rn, rk, /*stages=*/0, /*with_C=*/false};
    if (is_valid_ppu_tile(cand)) return cand;
  }
  return kDefaultTile;
}

// Stage count to request for a tile, or 0 to let CUTLASS auto-carveout decide.
//
// Auto-carveout under-provisions the 256x256 tile: it reserves room for the
// epilogue SharedStorage and settles on 2 stages (128 KB of the 256 KB budget),
// leaving 64 KB unused. Asking for 3 stages (192 KB) is worth 10.4% geomean
// over the 15 cases of the MoE sweep that land on this tile -- and 26% on the
// TN ones specifically. 4 stages measures another 0.15%, which is not worth
// giving up the last 64 KB of the budget for.
//
// 256x128 is left on auto, which already picks 4 stages (192 KB); explicit 3
// measured within noise of it.
//
// Note this is NOT an occupancy play. Cutting a tile to 2 stages does let a
// second CTA co-reside (residency 1 -> 2, occupancy 12.5% -> 25%), but on
// 256x128 it measured 26% SLOWER: the deeper mainloop pipeline buys more than
// the extra CTA does. Only stage counts that keep residency at 1 are worth
// considering.
int preferred_stages(int tile_m, int tile_n, int tile_k) {
  if (tile_k == 64 && tile_m == 256 && tile_n == 256) return 3;
  return 0;
}

// Exact configurations established by repeated shape-level tuning. Keep this
// table small: entries override the adaptive model only when the grouped GEMM
// signature falls into their inclusive (m, n, k, layout) ranges, and every
// value must exist in NVTE_GG_TILE_TABLE. N is lower-bounded by the tuned
// regime and unbounded above; most K ranges use a narrow +/-12.5% envelope
// around each tuned shape, while the NT wgrad K range covers MPE from around
// 256 upward. NVTE_GG_NO_TUNED_TILE_OVERRIDES provides a clean A/B baseline.
//
// The key is deliberately z-free and every shape dimension is matched as an
// inclusive range instead of the old (num_groups == 16, exact shape) pin. The
// old pin silently missed other expert counts and small training-time shape
// fluctuations, dropping those launches to the adaptive path, whose NN
// re-route to BK=128 s2 (see below) measured 12-25% slower than these entries
// on the same shapes. Two observations justify generalizing M:
//   1. z is a common multiplier on every candidate tile's cost: the
//      persistent kernel runs z * ceil(m/BM) * ceil(n/BN) blocks and the
//      wave count ceil(blocks / num_sms) scales all candidates together,
//      so the argmin over the tile menu does not depend on z. For these
//      FFN shapes even z=1 overfills a wave ((2048,1536) at 256x256 is 48
//      blocks on 39 CUs), so the tuned winner holds from z=1 up.
//   2. For m >= tile_m every tile row is live: the per-block cost is then
//      independent of m (the block count scales linearly in m, per-block
//      time does not), so a winner measured at mpe=2048 generalizes to any
//      deeper mpe. Deep entries therefore take m_lo = 256 = tile_m.
// The shallow dgrad entry keeps the m <= 160 envelope of the DeepGemm
// memory-bound analog below. The (160, 256) gap has no measurements and
// falls through to the adaptive selector.
struct TunedTileEntry {
  int m_lo;  // inclusive lower bound on avg per-expert M
  int m_hi;  // inclusive upper bound (INT_MAX = unbounded)
  int n_lo;  // inclusive lower bound on avg N
  int n_hi;  // inclusive upper bound on avg N
  int k_lo;  // inclusive lower bound on avg K
  int k_hi;  // inclusive upper bound on avg K
  bool trans_a;
  bool trans_b;
  int sm_arch;
  int tile_m;
  int tile_n;
  int tile_k;
  int stages;
  // Zero preserves the default grid policy. Non-zero values are only honored
  // for the measured 64-CU, z=16 sm80 production configuration.
  int workers_per_cu = 0;
};

