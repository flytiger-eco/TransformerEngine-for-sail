template <bool trans_a, bool trans_b, int SmArch,
          typename Element = cutlass::bfloat16_t,
          int TileM = 256, int TileN = 128, int TileK = 64, int Stages = 0>
void launch_grouped_gemm_rtc(const NVTETensor* A, const NVTETensor* B,
                             NVTETensor* D, NVTETensor* workspace, float alpha,
                             float beta, int num_gemms, int sm_arch,
                             int math_sm_count, cudaStream_t stream,
                             TileConfig const& cfg) {
  using Traits = GemmTraits<trans_a, trans_b, SmArch, Element,
                            TileM, TileN, TileK, Stages>;
  using GemmKernel = typename Traits::GemmKernel;

  using ElementA = typename Traits::ElementA;
  using ElementB = typename Traits::ElementB;
  using ElementC = typename Traits::ElementC;
  using ElementD = typename Traits::ElementD;
  using LayoutA = typename Traits::LayoutA;
  using LayoutB = typename Traits::LayoutB;
  using LayoutC = typename Traits::LayoutC;
  using ProblemShape = typename Traits::ProblemShape;
  using ProblemShapeType = typename Traits::ProblemShapeType;
  using InternalStrideA = typename GemmKernel::InternalStrideA;
  using InternalStrideB = typename GemmKernel::InternalStrideB;
  using InternalStrideC = typename GemmKernel::InternalStrideC;
  using InternalStrideD = typename GemmKernel::InternalStrideD;

  // Workspace layout (mirrors static path in cutlass_grouped_gemm.cuh):
  //   [gemm_coord_size]  ProblemShapeType[num_gemms]
  //   [ptr_size]         ElementA*[num_gemms]
  //   [ptr_size]         ElementB*[num_gemms]
  //   [ptr_size]         ElementC*[num_gemms]
  //   [ptr_size]         ElementD*[num_gemms]
  //   [ldd_size]         InternalStrideA[num_gemms]
  //   [ldd_size]         InternalStrideB[num_gemms]
  //   [ldd_size]         InternalStrideC[num_gemms]
  //   [ldd_size]         InternalStrideD[num_gemms]
  //   [kernel_ws_size]   kernel workspace for to_underlying_arguments
  //
  // The static path passes a valid device pointer for kernel workspace even
  // when get_workspace_size() returns 0. Some PPU scheduler/epilogue code
  // checks the pointer itself (not just the size), so passing nullptr can lead
  // to "invalid page" crashes after repeated launches. Reserve a small aligned
  // region to keep the pointer valid.
  const size_t gemm_coord_size = round_up(num_gemms * sizeof(ProblemShapeType), 128UL);
  const size_t ptr_bytes = round_up(num_gemms * sizeof(void*), 128UL);
  const size_t ldd_bytes = round_up(num_gemms * sizeof(int64_t), 128UL);
  const size_t param_workspace_size =
      gemm_coord_size + 4 * ptr_bytes + 4 * ldd_bytes;
  // Keep a valid aligned kernel-workspace pointer even when the kernel reports
  // zero bytes; some PPU scheduler/epilogue code checks the pointer itself.
  constexpr size_t kMinKernelWorkspace = 128UL;

  Tensor* wspace = convertNVTETensor(workspace[0]);
  NVTE_CHECK(wspace != nullptr, "RTC grouped GEMM requires workspace[0].");
  char* dev_ws = reinterpret_cast<char*>(wspace->data.dptr);

  // The staging ring reuses pinned slots guarded by host-side events, and the
  // launch path issues driver-API calls (function attributes, module loads).
  // Capturing that into a CUDA graph would replay a slot whose contents the
  // next host-side launch already overwrote (and the driver calls would fail),
  // so reject capture explicitly instead of producing a silently wrong graph.
  cudaStreamCaptureStatus capture_status = cudaStreamCaptureStatusNone;
  NVTE_CHECK_CUDA(cudaStreamIsCapturing(stream, &capture_status));
  NVTE_CHECK(capture_status == cudaStreamCaptureStatusNone,
             "CUTLASS RTC grouped GEMM does not support CUDA graph capture; "
             "disable the RTC arm (NVTE_USE_CUTLASS_GROUPED_GEMM_RTC=0) when "
             "capturing.");

  // Acquire a staging slot from the pinned ring. The pageable heap fallback
  // covers machines without the ring and call shapes whose parameter block
  // does not fit a slot (huge num_gemms): the driver captures pageable
  // sources synchronously before cudaMemcpyAsync returns, so a per-call
  // buffer is race-free even though it dies at function exit.
  std::vector<char> host_ws_heap;
  char* host_ws = nullptr;
  int ws_slot = -1;
  HostWsRing& ws_ring = host_ws_ring(current_device_ordinal());
  if (ws_ring.base != nullptr && param_workspace_size <= kHostWsSlotSize) {
    cudaEvent_t slot_event = nullptr;
    {
      std::lock_guard<std::mutex> lock(ws_ring.mutex);
      ws_slot = ws_ring.next;
      ws_ring.next = (ws_ring.next + 1) % kHostWsSlots;
      if (ws_ring.recorded[ws_slot]) slot_event = ws_ring.events[ws_slot];
    }
    // Reuse the slot only after the previous consumer's H2D copy completed.
    if (slot_event != nullptr) {
      NVTE_CHECK_CUDA(cudaEventSynchronize(slot_event));
    }
    host_ws = ws_ring.base + ws_slot * kHostWsSlotSize;
  } else {
    host_ws_heap.resize(param_workspace_size);
    host_ws = host_ws_heap.data();
  }

  // Host-side arrays. Every view into the staging buffer is (re)bound through
  // this lambda: the buffer may be reallocated below once the total workspace
  // size is known, and stale views into the old allocation would feed the
  // kernel freelist/garbage shapes.
  ProblemShapeType* h_shapes = nullptr;
  ElementA** h_ptr_A = nullptr;
  ElementB** h_ptr_B = nullptr;
  ElementC** h_ptr_C = nullptr;
  ElementD** h_ptr_D = nullptr;
  int64_t* h_lda = nullptr;
  int64_t* h_ldb = nullptr;
  int64_t* h_ldc = nullptr;
  int64_t* h_ldd = nullptr;
  auto bind_host_arrays = [&](char* base) {
    h_shapes = reinterpret_cast<ProblemShapeType*>(base);
    h_ptr_A = reinterpret_cast<ElementA**>(base + gemm_coord_size);
    h_ptr_B = reinterpret_cast<ElementB**>(base + gemm_coord_size + 1 * ptr_bytes);
    h_ptr_C = reinterpret_cast<ElementC**>(base + gemm_coord_size + 2 * ptr_bytes);
    h_ptr_D = reinterpret_cast<ElementD**>(base + gemm_coord_size + 3 * ptr_bytes);
    h_lda = reinterpret_cast<int64_t*>(base + gemm_coord_size + 4 * ptr_bytes + 0 * ldd_bytes);
    h_ldb = reinterpret_cast<int64_t*>(base + gemm_coord_size + 4 * ptr_bytes + 1 * ldd_bytes);
    h_ldc = reinterpret_cast<int64_t*>(base + gemm_coord_size + 4 * ptr_bytes + 2 * ldd_bytes);
    h_ldd = reinterpret_cast<int64_t*>(base + gemm_coord_size + 4 * ptr_bytes + 3 * ldd_bytes);
  };
  bind_host_arrays(host_ws);

  for (int i = 0; i < num_gemms; ++i) {
    const Tensor* inputA = convertNVTETensorCheck(A[i]);
    const Tensor* inputB = convertNVTETensorCheck(B[i]);
    Tensor* outputD = convertNVTETensor(D[i]);

    // Compute per-group (m, n, k) matching the static path
    // (cutlass_grouped_gemm.cuh). After the caller's A/B swap, inputA = ext B
    // and inputB = ext A. M and K come from inputA; N comes from inputB.
    const int m = trans_a ? static_cast<int>(inputA->data.shape[1])
                          : static_cast<int>(inputA->data.shape[0]);
    const int k = trans_a ? static_cast<int>(inputA->data.shape[0])
                          : static_cast<int>(inputA->data.shape[1]);
    const int n = trans_b ? static_cast<int>(inputB->data.shape[0])
                          : static_cast<int>(inputB->data.shape[1]);

    h_shapes[i] = ProblemShapeType(m, n, k);

    h_ptr_A[i] = reinterpret_cast<ElementA*>(inputA->data.dptr);
    h_ptr_B[i] = reinterpret_cast<ElementB*>(inputB->data.dptr);
    h_ptr_C[i] = reinterpret_cast<ElementC*>(outputD->data.dptr);
    h_ptr_D[i] = reinterpret_cast<ElementD*>(outputD->data.dptr);

    // Per-group leading dimensions (matches static path).
    h_lda[i] = LayoutA::packed({m, k}).stride(0);
    h_ldb[i] = LayoutB::packed({k, n}).stride(0);
    h_ldc[i] = LayoutC::packed({m, n}).stride(0);
    h_ldd[i] = LayoutC::packed({m, n}).stride(0);
  }

  // Device-side pointers into the workspace.
  ProblemShapeType* d_shapes =
      reinterpret_cast<ProblemShapeType*>(dev_ws);
  ElementA const** d_ptr_A =
      reinterpret_cast<ElementA const**>(dev_ws + gemm_coord_size);
  ElementB const** d_ptr_B =
      reinterpret_cast<ElementB const**>(dev_ws + gemm_coord_size + 1 * ptr_bytes);
  ElementC const** d_ptr_C =
      reinterpret_cast<ElementC const**>(dev_ws + gemm_coord_size + 2 * ptr_bytes);
  ElementD** d_ptr_D =
      reinterpret_cast<ElementD**>(dev_ws + gemm_coord_size + 3 * ptr_bytes);
  InternalStrideA* d_lda =
      reinterpret_cast<InternalStrideA*>(dev_ws + gemm_coord_size + 4 * ptr_bytes + 0 * ldd_bytes);
  InternalStrideB* d_ldb =
      reinterpret_cast<InternalStrideB*>(dev_ws + gemm_coord_size + 4 * ptr_bytes + 1 * ldd_bytes);
  InternalStrideC* d_ldc =
      reinterpret_cast<InternalStrideC*>(dev_ws + gemm_coord_size + 4 * ptr_bytes + 2 * ldd_bytes);
  InternalStrideD* d_ldd =
      reinterpret_cast<InternalStrideD*>(dev_ws + gemm_coord_size + 4 * ptr_bytes + 3 * ldd_bytes);

  // Construct GroupProblemShape with device + host pointers.
  ProblemShape problem_shape;
  problem_shape.num_groups = num_gemms;
  problem_shape.problem_shapes = d_shapes;
  problem_shape.host_problem_shapes = h_shapes;

  typename GemmKernel::EpilogueArguments epilogue_args{};
  auto& fusion_args = epilogue_args.thread;
  fusion_args.alpha = alpha;
  fusion_args.beta = beta;
  fusion_args.alpha_ptr = nullptr;
  fusion_args.beta_ptr = nullptr;
  fusion_args.alpha_ptr_array = nullptr;
  fusion_args.beta_ptr_array = nullptr;
  fusion_args.dAlpha = {cute::_0{}, cute::_0{}, 0};
  fusion_args.dBeta = {cute::_0{}, cute::_0{}, 0};
  epilogue_args.ptr_C = (cfg.with_C && beta > 0.0f) ? d_ptr_C : nullptr;
  epilogue_args.dC = d_ldc;
  epilogue_args.ptr_D = d_ptr_D;
  epilogue_args.dD = d_ldd;

  typename GemmKernel::Arguments args{};
  args.mode = cutlass::gemm::GemmUniversalMode::kGrouped;
  args.problem_shape = problem_shape;
  args.mainloop = {d_ptr_A, d_lda, d_ptr_B, d_ldb};
  args.epilogue = epilogue_args;
  args.hw_info = cutlass::KernelHardwareInfo{};

  // Set hw_info.sm_count BEFORE to_underlying_arguments so the scheduler
  // uses the correct SM count during initialization.  On PPU, the default
  // query_device_multiprocessor_count may return 0.
  {
    int effective_sm = math_sm_count;
    if (effective_sm <= 0) {
      effective_sm = transformer_engine::cuda::sm_count();
    }
    if (effective_sm <= 0) {
      effective_sm = 39;  // PPU SM89 fallback
    }
    // The scheduler sizes the persistent grid at one CTA per CU. Overstating
    // the CU count only queues extra CTAs and repeats prologue/epilogue work.
    args.hw_info.cu_count = effective_sm;
  }

  if (!GemmKernel::can_implement(args)) {
    NVTE_ERROR("CUTLASS RTC grouped GEMM: GemmKernel::can_implement failed "
               "for num_gemms=", num_gemms, ".");
  }

  const size_t required_kernel_workspace = GemmKernel::get_workspace_size(args);
  const size_t kernel_workspace_size = round_up(
      std::max(kMinKernelWorkspace, required_kernel_workspace), 128UL);
  const size_t total_workspace_size = param_workspace_size + kernel_workspace_size;
  NVTE_CHECK(total_workspace_size <= kCPUWorkSpaceSize,
             "Insufficient CPU workspace for RTC grouped GEMM (required=",
             total_workspace_size, ", available=", kCPUWorkSpaceSize, ").");
  NVTE_CHECK(total_workspace_size <= static_cast<size_t>(wspace->numel()),
             "Insufficient device workspace for RTC grouped GEMM (required=",
             static_cast<int64_t>(total_workspace_size),
             ", available=", static_cast<int64_t>(wspace->numel()), ").");

  // Copy parameters and a zeroed kernel-workspace region in one H2D transfer.
  if (ws_slot >= 0 && total_workspace_size > kHostWsSlotSize) {
    // Oversized blob (huge num_gemms): re-stage from the pageable heap
    // buffer. Nothing async reads the slot, so it needs no event.
    host_ws_heap.assign(host_ws, host_ws + param_workspace_size);
    ws_slot = -1;
  }
  if (ws_slot < 0) {
    // Pageable staging (no pinned ring, or oversized blob): the driver
    // captures pageable sources synchronously before cudaMemcpyAsync
    // returns, so the per-call buffer is race-free. resize() preserves the
    // parameter bytes already staged in it, but it may move the allocation:
    // rebind every view (and the args copy the kernel's workspace helpers
    // read host shapes from) so nothing points into the freed buffer.
    host_ws_heap.resize(total_workspace_size);
    host_ws = host_ws_heap.data();
    bind_host_arrays(host_ws);
    problem_shape.host_problem_shapes = h_shapes;
    args.problem_shape.host_problem_shapes = h_shapes;
  }
  std::memset(host_ws + param_workspace_size, 0, kernel_workspace_size);
  NVTE_CHECK_CUDA(cudaMemcpyAsync(dev_ws, host_ws, total_workspace_size,
                                  cudaMemcpyHostToDevice, stream));
  if (ws_slot >= 0) {
    // The H2D copy may sit queued behind prior stream work; keep the slot
    // reserved until it executed, otherwise the next call's host-side
    // staging would overwrite it first.
    std::lock_guard<std::mutex> lock(ws_ring.mutex);
    NVTE_CHECK_CUDA(cudaEventRecord(ws_ring.events[ws_slot], stream));
    ws_ring.recorded[ws_slot] = true;
  }

  // Pass the same sized and initialized workspace used by the kernel's
  // to_underlying_arguments() split.
  void* kernel_workspace = dev_ws + param_workspace_size;
  if (GemmKernel::initialize_workspace(args, kernel_workspace, stream) !=
      cutlass::Status::kSuccess) {
    NVTE_ERROR("CUTLASS RTC grouped GEMM: workspace initialization failed "
               "for num_gemms=", num_gemms, ".");
  }
  typename GemmKernel::Params params =
      GemmKernel::to_underlying_arguments(args, kernel_workspace);

  const CompiledKernel& kernel =
      get_or_compile<Traits>(sm_arch, trans_a, trans_b, cfg);

  if (kernel.smem_size >= (48 << 10)) {
    NVTE_CALL_CHECK_CUDA_DRIVER(cuFuncSetAttribute, kernel.function,
                                CU_FUNC_ATTRIBUTE_MAX_DYNAMIC_SHARED_SIZE_BYTES,
                                kernel.smem_size);
  }
  // Grid MUST come from the scheduler. The GroupScheduler linearizes every
  // group's tiles into problem_blocks=(total_ctas,1,1), so its rasterization
  // heuristic picks AlongN (tiles_n=1 is not > tiles_m), and for AlongN with
  // cluster_size==1 get_grid_shape() returns (1, min(sm_count,total), 1).
  // The scheduler then decodes `cluster_minor_offset = blockIdx.x`, expecting
  // blockIdx.x to be the CTA's offset *inside a cluster* -- i.e. always 0 here.
  // Launching (total_ctas,1,1) instead feeds the global linear tile index into
  // that field, so minor_work_idx runs far past the problem and the mainloop's
  // async copies fault (or silently read out of bounds).
  uint32_t total_ctas = 0;
  for (int g = 0; g < num_gemms; g++) {
    const int gm = cute::get<0>(h_shapes[g]);
    const int gn = cute::get<1>(h_shapes[g]);
    const int ctas_m = (gm + cfg.tile_m - 1) / cfg.tile_m;
    const int ctas_n = (gn + cfg.tile_n - 1) / cfg.tile_n;
    total_ctas += static_cast<uint32_t>(ctas_m * ctas_n);
  }

  dim3 grid = GemmKernel::get_grid_shape(params);
  const bool raster_along_n =
      (params.scheduler.raster_order_ ==
       decltype(params.scheduler)::RasterOrder::AlongN);
  // The scheduler is a grid-stride persistent loop: each CTA starts at its
  // linearized blockIdx and advance_to_next_work() adds total_grid_size_ (=the
  // launched gridDim). Any grid size <= total_ctas covers every tile exactly
  // once. Tuned worker counts and occupancy-derived grids must be applied on
  // the non-cluster-minor dimension; otherwise the scheduler can index past
  // the problem for AlongN/AlongM rasterization.
  auto set_grid_1d = [&](uint32_t n) {
    n = n > 0 ? n : 1;
    grid = raster_along_n ? dim3(1, n, 1) : dim3(n, 1, 1);
  };

  // Tuned worker counts are production data carried by the matched table row.
  // Limit them to the measured hardware/workload envelope; all sm89 and other
  // sm80 configurations retain their previous default/occupancy grid policy.
  int workers_per_cu = 0;
  if (SmArch == 80 && args.hw_info.cu_count == 64 && num_gemms == 16 &&
      cfg.workers_per_cu > 0) {
    // MoE routing makes the per-expert token count dynamic. For TN/NN that is
    // the GEMM M dimension; for NT/wgrad it is K. Keep only the model dimensions
    // uniform so a row selected by average MPE also applies to imbalanced experts.
    bool compatible_shapes = true;
    for (int g = 1; g < num_gemms; ++g) {
      if constexpr (trans_a && !trans_b) {
        compatible_shapes =
            cute::get<0>(h_shapes[g]) == cute::get<0>(h_shapes[0]) &&
            cute::get<1>(h_shapes[g]) == cute::get<1>(h_shapes[0]);
      } else {
        compatible_shapes =
            cute::get<1>(h_shapes[g]) == cute::get<1>(h_shapes[0]) &&
            cute::get<2>(h_shapes[g]) == cute::get<2>(h_shapes[0]);
      }
      if (!compatible_shapes) break;
    }
    if (compatible_shapes) workers_per_cu = cfg.workers_per_cu;
  }
  if (workers_per_cu <= 0 && cfg.tile_m <= 128) {
    // Auto multi-CTA residency for 128-row tiles that do not carry a tuned
    // worker count. Filling available resident slots overlaps the next tile's
    // pipeline fill with the current tile's epilogue.
    int occ = 0;
    if (cuOccupancyMaxActiveBlocksPerMultiprocessor(
            &occ, kernel.function, static_cast<int>(kernel.thread_count),
            static_cast<size_t>(kernel.smem_size)) == CUDA_SUCCESS &&
        occ > 0) {
      workers_per_cu = occ;
    }
  }
  if (workers_per_cu > 0) {
    uint64_t want = uint64_t(args.hw_info.cu_count) * uint64_t(workers_per_cu);
    if (total_ctas > 0 && want > total_ctas) want = total_ctas;
    set_grid_1d(static_cast<uint32_t>(want));
  }
  dim3 block(kernel.thread_count, 1, 1);

  // HGTX per-launch tag (DeepGemm-style three-piece). Group extents come from
  // the host problem shapes, so the tag carries the real per-group
  // distribution with no D2H sync. Push must pair with pop on the same host
  // thread around the launch; the guard keeps them paired across exceptions.
  te_profiling::TeProfParam te_prof;
  if (te_profiling::TeProfilingInterface::Instance().enabled()) {
    int te_dev = 0;
    cudaGetDevice(&te_dev);
    std::vector<int> te_m(num_gemms), te_n(num_gemms), te_k(num_gemms);
    for (int g = 0; g < num_gemms; ++g) {
      te_m[g] = cute::get<0>(h_shapes[g]);
      te_n[g] = cute::get<1>(h_shapes[g]);
      te_k[g] = cute::get<2>(h_shapes[g]);
    }
    const int te_tile[4] = {cfg.tile_m, cfg.tile_n, cfg.tile_k, cfg.stages};
    te_prof.set_grouped_gemm(
        "GroupedGemmRtc", element_short<ElementA>(), num_gemms,
        trans_a ? (trans_b ? "TT" : "TN") : (trans_b ? "NT" : "NN"),
        beta != 0.0f, te_m.data(), te_n.data(), te_k.data(), te_tile, te_dev,
        stream);
  }

  void* kargs[] = {&params};
  {
    te_profiling::TeHgtxGuard te_prof_guard(te_prof);
    NVTE_CALL_CHECK_CUDA_DRIVER(cuLaunchKernel, kernel.function, grid.x, grid.y,
                                grid.z, block.x, block.y, block.z,
                                static_cast<unsigned>(kernel.smem_size),
                                static_cast<CUstream>(stream), kargs, nullptr);
  }
  if (verbose_tile_debug()) {
    NVTE_WARN("CUTLASS RTC grouped GEMM LAUNCHED:\n  kernel=",
              make_kernel_label<Traits>(sm_arch, cfg),
              "\n  kernel_func=0x",
              reinterpret_cast<uintptr_t>(kernel.function),
              " grid=(", grid.x, ",", grid.y, ",", grid.z, ")",
              " block=(", block.x, ",", block.y, ",", block.z, ")",
              " smem=", kernel.smem_size, "B  num_gemms=", num_gemms,
              " tile=(", cfg.tile_m, ",", cfg.tile_n, ",", cfg.tile_k, ")",
              " stages=", cfg.stages, " with_C=", cfg.with_C);
  }
}

// ---------------------------------------------------------------------------
// Public C++ entry point (called from cublaslt_gemm.cu)
// ---------------------------------------------------------------------------

bool dispatch(const NVTETensor* A, const NVTETensor* B, NVTETensor* D,
              int num_gemms, bool transa, bool transb, NVTETensor* workspace,
              bool accumulate, int device, int math_sm_count,
              cudaStream_t stream) {
  const Tensor* inputA = convertNVTETensorCheck(A[0]);
  const bool is_bf16 = (inputA->data.dtype == DType::kBFloat16);
  const bool is_fp16 = (inputA->data.dtype == DType::kFloat16);
  if (!is_bf16 && !is_fp16) return false;

  const int sm_arch = cuda::sm_arch(device);
  if (sm_arch != 80 && sm_arch != 89) return false;

  if (num_gemms <= 0) return false;

  // Sweep all groups to collect per-group (M, N, K) and compute averages for
  // the tile heuristic. launch_grouped_gemm_rtc is called with the (A, B)
  // operands swapped and the trans flags swapped accordingly (see
  // dispatch_layout below), so the TRUE GEMM shape is: input-role tensor B[i]
  // supplies M/K, weight-role tensor A[i] supplies N, under swapped trans
  // flags (ta = transb, tb = transa). Reading A[i] for M/K here — as an
  // earlier version did — mislabels the axes (e.g. reports avg_shape=(K,K,N)
  // and drops the real M entirely), which is harmless for a shape-agnostic
  // fixed tile but wrong for the shape-sensitive adaptive heuristic.
  const bool ta = transb;
  const bool tb = transa;
  int64_t sum_m = 0, sum_n = 0, sum_k = 0;
  for (int i = 0; i < num_gemms; ++i) {
    const Tensor* tin = convertNVTETensorCheck(B[i]);  // input  (M, K)
    const Tensor* twt = convertNVTETensorCheck(A[i]);  // weight (N)
    const int m = ta ? static_cast<int>(tin->data.shape[1])
                     : static_cast<int>(tin->data.shape[0]);
    const int k = ta ? static_cast<int>(tin->data.shape[0])
                     : static_cast<int>(tin->data.shape[1]);
    const int n = tb ? static_cast<int>(twt->data.shape[0])
                     : static_cast<int>(twt->data.shape[1]);
    sum_m += m;
    sum_n += n;
    sum_k += k;
  }
  const int avg_m = static_cast<int>(sum_m / num_gemms);
  const int avg_n = static_cast<int>(sum_n / num_gemms);
  const int avg_k = static_cast<int>(sum_k / num_gemms);

  // CU count for the adaptive heuristic: prefer the caller's math_sm_count,
  // then the device query, then the PPU SM89 default.
  int num_sms = math_sm_count;
  if (num_sms <= 0) num_sms = cuda::sm_count();
  if (num_sms <= 0) num_sms = 39;

  // ElementC=bf16 by default. We originally compiled ElementC=void when
  // accumulate=false to statically elide the source-C load — but on PPU
  // this is ~12% SLOWER than ElementC=bf16 + the runtime fast-path
  // (`is_source_needed() == false` when beta=0) (verified via asys traces:
  // void cubin = 8.23 ms vs bf16 cubin = 7.35 ms on the MoE workload).
  // The PPU epilogue's `ScaleType::Nothing` branch (selected when
  // ElementC_=void in ppu_builder.inl) appears less optimized than the
  // `OnlyAlphaScaling` branch + runtime beta=0 short-circuit.
  // NVTE_GG_FORCE_WITH_C=0 opts back into the void path for experimentation.
  // Route toggles are parsed once per process (per-launch istringstream getenv
  // is measurable host time on this path).
  bool with_C = true;
  static const std::string with_c_env = getenv<std::string>("NVTE_GG_FORCE_WITH_C");
  if (!with_c_env.empty()) {
    with_C = (with_c_env == "1" || with_c_env == "true" || with_c_env == "TRUE");
  }
  TileConfig cfg = get_or_query_tile_stages(avg_m, avg_n, avg_k, num_gemms,
                                            transa, transb, sm_arch, num_sms,
                                            with_C);
  // DeepGemm's memory-bound region analog (m <= 160): when every group's
  // M fits in half of a 256-row tile, an M-matched 128-row tile removes the
  // 2x M-direction waste (measured on problem_shapes.txt z=16, mpe=128, NN:
  // geomean TE/DeepGemm 0.58 -> 0.65). BN follows the tile count: N <= 512
  // keeps 256-wide tiles (fewer tiles, one wave per expert), N > 512 prefers
  // 128-wide tiles (2x the tiles for load balance, and the 64 KB smem
  // footprint lets 3-4 CTAs co-reside per CU — the occupancy auto path in
  // launch_grouped_gemm_rtc turns that into the second half of the win,
  // 0.65 -> 0.81). Skipped when NVTE_GG_FORCE_TILE asks for something
  // specific.
  static const std::string force_tile_env_caller =
      getenv<std::string>("NVTE_GG_FORCE_TILE");
  if (force_tile_env_caller.empty() && avg_m > 0 && avg_m <= 160) {
    // A tuned-table entry (a per-case validated winner) outranks the
    // generic small_m template below; without this guard the template
    // silently overrides the table for every mpe<=160 shape. Re-querying the
    // table here is nanoseconds vs. the launch it gates.
    TileConfig tuned;
    if (!lookup_tuned_tile(avg_m, avg_n, avg_k, transa, transb, sm_arch,
                           with_C, &tuned)) {
      TileConfig small_m{128, (avg_n <= 512) ? 256 : 128, 64, 2, with_C};
      if (has_host_instantiation(small_m)) {
        cfg = small_m;
      }
    }
  }
  if (!is_valid_ppu_tile(cfg)) {
    if (verbose_tile_debug()) {
      NVTE_WARN("CUTLASS RTC grouped GEMM: heuristic returned invalid PPU "
                "tile (", cfg.tile_m, ",", cfg.tile_n, ",", cfg.tile_k,
                ") stages=", cfg.stages,
                "; falling back to default (256,256,64)/s3.");
    }
    cfg = kDefaultTile;
    cfg.with_C = with_C;
  }

  // The host must instantiate GemmTraits for the same tile and stage count as
  // the cubin. Any unsupported pair falls back to the one fixed default rather
  // than changing only its stage count, so every fallback path is consistent.
  if (!has_host_instantiation(cfg)) {
    if (verbose_tile_debug()) {
      NVTE_WARN("CUTLASS RTC grouped GEMM: tile (", cfg.tile_m, ",",
                cfg.tile_n, ",", cfg.tile_k, ") stages=", cfg.stages,
                " has no host instantiation; falling back to default "
                "(256,256,64)/s3.");
    }
    cfg = TileConfig{kDefaultTile.tile_m, kDefaultTile.tile_n,
                     kDefaultTile.tile_k, kDefaultTile.stages, cfg.with_C};
  }

  if (verbose_tile_debug()) {
    NVTE_WARN("CUTLASS RTC grouped GEMM dispatch: num_gemms=", num_gemms,
              " sm_arch=", sm_arch, " transa=", transa, " transb=", transb,
              " accumulate=", accumulate,
              " avg_shape=(", avg_m, ",", avg_n, ",", avg_k, ")",
              " tile=(", cfg.tile_m, ",", cfg.tile_n, ",",
              cfg.tile_k, ") stages=", cfg.stages, " with_C=", cfg.with_C);
  }

  float alpha = 1.0f;
  float beta = accumulate ? 1.0f : 0.0f;

  // cuBLAS/CUTLASS convention swap (A,B) — matches cutlass_grouped_gemm.
  // cfg has been snapped to a (tile, stages) pair this table covers, so a miss
  // is a bug in the snap above, not a user error — hence the hard error at the
  // end rather than a fallback. Falling through used to return without ever
  // launching, which reported success and produced a silently untouched D.
  auto run = [&](auto ta_const, auto tb_const, auto arch_const) {
    constexpr bool ta = decltype(ta_const)::value;
    constexpr bool tb = decltype(tb_const)::value;
    constexpr int Arch = decltype(arch_const)::value;
#define NVTE_GG_LAUNCH_TILE_STAGES(TM, TN, TK, ST)                             \
  if (cfg.tile_m == (TM) && cfg.tile_n == (TN) && cfg.tile_k == (TK) &&        \
      cfg.stages == (ST)) {                                                    \
    if (is_fp16) {                                                            \
      launch_grouped_gemm_rtc<ta, tb, Arch, cutlass::half_t, TM, TN, TK, ST>(  \
          B, A, D, workspace, alpha, beta, num_gemms, Arch, math_sm_count,     \
          stream, cfg);                                                        \
    } else {                                                                  \
      launch_grouped_gemm_rtc<ta, tb, Arch, cutlass::bfloat16_t, TM, TN, TK,   \
                              ST>(B, A, D, workspace, alpha, beta, num_gemms,   \
                                  Arch, math_sm_count, stream, cfg);           \
    }                                                                          \
    return;                                                                    \
  }
    // One entry per NVTE_GG_TILE_TABLE row; has_host_instantiation() above
    // gates on the same list, so the hard error below is unreachable unless the
    // two expansions were split by hand again.
    NVTE_GG_TILE_TABLE(NVTE_GG_LAUNCH_TILE_STAGES)
#undef NVTE_GG_LAUNCH_TILE_STAGES
    NVTE_ERROR("CUTLASS RTC grouped GEMM: no host instantiation for tile=(",
               cfg.tile_m, ",", cfg.tile_n, ",", cfg.tile_k, ") stages=",
               cfg.stages,
               ". get_or_query_tile_stages() is supposed to snap cfg onto the "
               "dispatch table; the two have drifted apart.");
  };

  auto dispatch_layout = [&](auto arch_const) -> bool {
    using F = std::false_type;
    using T = std::true_type;
    if (!transa && !transb) { run(F{}, F{}, arch_const); return true; }
    if (!transb && transa)  { run(F{}, T{}, arch_const); return true; }
    if (transb && !transa)  { run(T{}, F{}, arch_const); return true; }
    return false;  // TT not supported
  };

  bool ok = false;
  if (sm_arch == 80) {
    ok = dispatch_layout(std::integral_constant<int, 80>{});
  } else {
    ok = dispatch_layout(std::integral_constant<int, 89>{});
  }
  return ok;
}

}  // namespace grouped_gemm_rtc
}  // namespace transformer_engine

bool cutlass_grouped_gemm_rtc(const NVTETensor* A, const NVTETensor* B,
                              NVTETensor* D, int num_gemms, bool transa,
                              bool transb, bool /*grad*/, NVTETensor* workspace,
                              bool accumulate, int device, int math_sm_count,
                              cudaStream_t stream) {
  try {
    return transformer_engine::grouped_gemm_rtc::dispatch(
        A, B, D, num_gemms, transa, transb, workspace, accumulate, device,
        math_sm_count, stream);
  } catch (const std::exception& e) {
    if (transformer_engine::getenv<bool>(
            "NVTE_CUTLASS_GROUPED_GEMM_WARN_FALLBACK", false)) {
      NVTE_WARN("CUTLASS RTC grouped GEMM failed: ", e.what());
    }
    return false;
  }
}
