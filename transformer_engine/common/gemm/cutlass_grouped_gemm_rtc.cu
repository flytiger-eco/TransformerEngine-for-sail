// Load a cubin image into the current context and resolve the kernel.
CompiledKernel load_cubin_module(const std::string& cubin,
                                 const std::string& mangled) {
  cuda_driver::ensure_context_exists();
  CUmodule module = nullptr;
  NVTE_CALL_CHECK_CUDA_DRIVER(cuModuleLoadDataEx, &module, cubin.data(), 0,
                              nullptr, nullptr);
  CUfunction func = nullptr;
  NVTE_CALL_CHECK_CUDA_DRIVER(cuModuleGetFunction, &func, module,
                              mangled.c_str());

  CompiledKernel ck;
  ck.module = module;
  ck.function = func;
  return ck;
}

std::vector<std::string> make_nvrtc_options(int sm_arch, bool trans_a, bool trans_b,
                                            TileConfig const& cfg, int dtype_id) {
  const std::string cuda_include = cuda::include_directory(true);
  const std::string cutlass_include = get_cutlass_include_dir();
  const std::string cccl_include = cuda_include + "/cccl";
  const std::string ppu_sdk_include =
      "/usr/local/PPU_SDK/targets/x86_64-linux/include";

  // SM-arch differentiation: matches the per-source compile options on
  // cutlass_grouped_gemm_ppu.cu in CMakeLists.txt.
  // sm80 -> sm_80a (ArchTag PPU0010, PPU 1.0 intrinsics)
  // sm89 -> sm_89  (ArchTag PPU0015, PPU 1.5 intrinsics)
  const std::string opt_arch = (sm_arch == 80)
      ? std::string("--gpu-architecture=sm_80a")
      : concat_strings("--gpu-architecture=sm_", sm_arch);

  std::vector<std::string> opts = {
      // Disable hgrtc's on-disk compile cache. Its key is based only on the
      // top-level source string + compile options, so it cannot see changes in
      // #include'd headers. TE manages its own in-process cache keyed by a
      // digest of the full include tree (see get_rtc_source_digest()).
      "--no-cache",
      "--std=c++17",
      opt_arch,
      concat_strings("-I", cuda_include),
      concat_strings("-I", cccl_include),
      concat_strings("-I", cutlass_include),
      concat_strings("-I", ppu_sdk_include),
      concat_strings("-DNVTE_GG_TRANS_A=", trans_a ? 1 : 0),
      concat_strings("-DNVTE_GG_TRANS_B=", trans_b ? 1 : 0),
      // The kernel template turns this into the PPU0010 / PPU0015 ArchTag; that tag
      // is the only thing that decides which PPU generation's AIU/MMA atoms the
      // cubin is built from.
      concat_strings("-DNVTE_GG_ARCH=", sm_arch),
      concat_strings("-DNVTE_GG_DTYPE=", dtype_id),
      concat_strings("-DNVTE_GG_WITH_C=", cfg.with_C ? 1 : 0),
      concat_strings("-DNVTE_GG_TILE_M=", cfg.tile_m),
      concat_strings("-DNVTE_GG_TILE_N=", cfg.tile_n),
      concat_strings("-DNVTE_GG_TILE_K=", cfg.tile_k),
      concat_strings("-DNVTE_GG_STAGES=", cfg.stages),
      "-DCUTLASS_ENABLE_TENSOR_CORE_MMA=1",
      "-D__HGGC_FP16_H__=1",
      "-D_HGGC_FP16_H_=1",
      "-DHGGC_FP16_H=1",
      "-D__HGGC_BF16_H__=1",
      "-D__HGGC_BF16_HPP__=1",
      "-D__BF16_DEFINED__=1",
  };

  // Debug/experiment passthrough: NVTE_GG_EXTRA_DEFINES="-DX=1 -DY=2" is
  // forwarded verbatim to the NVRTC command line. It is part of the
  // options list, hence of the RTC cache key, so each experiment gets
  // its own cubin without manual cache surgery. An unset/empty env must
  // not contribute an empty-string option: hgrtc rejects it with
  // "unrecognized option" and the whole RTC path fails.
  const std::string extra_defines = getenv<std::string>("NVTE_GG_EXTRA_DEFINES");
  if (!extra_defines.empty()) {
    opts.push_back(extra_defines);
  }
  
  // Match the flags the statically built PPU CUTLASS TUs get (see
  // CUTLASS_KERNEL_SOURCES and the global CUDA flags in
  // transformer_engine/common/CMakeLists.txt). Without NDEBUG the cubin keeps
  // every CUTLASS_ASSERT and CuTe bounds check live, which is a large codegen
  // difference from the statically compiled kernel that is known to work.
  // Note: --expt-relaxed-constexpr is NOT accepted by hgrtc ("unrecognized
  // option"), so only the -D flags can be mirrored here.
  if (!getenv<bool>("NVTE_GG_NO_EXTRA_NVRTC_FLAGS", false)) {
    opts.push_back("-DNDEBUG");
    opts.push_back("-DUSE_SAIL=1");
  }

  // Line info for profilers. Off by default; it is only needed when profiling.
  //
  // What this does and does not buy you, measured on this SDK:
  //   * hgrtc accepts -lineinfo (and --generate-line-info); -g/-g1/
  //     -gline-tables-only/-gdwarf-N/-gembed-source/-main-file-name are all
  //     rejected as unrecognized options.
  //   * -lineinfo emits .debug_line/.debug_line_str only. There is no
  //     .debug_info compile unit, and acu requires one — with just the line
  //     table it still reports "compiled without debug line information" and
  //     imports no source. Only --device-debug (-G) makes hgrtc emit
  //     .debug_info, and that turns off optimization, so it is useless for
  //     performance work. For a source-annotated profile of optimized code,
  //     compile the dumped TU offline (nvcc -lineinfo -cubin) and load it via
  //     NVTE_GG_RTC_LOAD_CUBIN_DIR.
  if (getenv<bool>("NVTE_GG_RTC_LINEINFO", false)) {
    opts.push_back("-lineinfo");
  }

  return opts;
}

CompiledKernel compile_kernel(const std::string& key,
                              const std::string& kernel_symbol, int sm_arch,
                              bool trans_a, bool trans_b,
                              TileConfig const& cfg, int dtype_id,
                              const std::vector<std::string>& opts,
                              std::string* compiled_cubin = nullptr) {
  // Profiling escape hatch: load <dir>/<kernel_symbol>.cubin instead of running
  // NVRTC. The reason this exists is source correlation: hgrtc's -lineinfo only
  // emits .debug_line, and acu needs a .debug_info compile unit before it will
  // collect source (it warns "compiled without debug line information"
  // otherwise). The offline compiler does emit .debug_info, so building the very
  // same translation unit with
  //   nvcc -lineinfo -cubin -O3 -DNDEBUG --expt-relaxed-constexpr \
  //        --generate-code=arch=compute_89,code=sm_89 <the NVTE_GG_* -D flags>
  // and pointing this variable at the output gives a profile of optimized code
  // that is annotated with CUDA source. Dump the exact TU with
  // NVTE_GG_RTC_LINEINFO=1 so the two cannot drift.
  //
  // A missing file is not fatal — we just compile normally — but a cubin
  // without the expected symbol is, courtesy of cuModuleGetFunction.
  if (auto dir = getenv<std::string>("NVTE_GG_RTC_LOAD_CUBIN_DIR");
      !dir.empty()) {
    const std::string path = dir + "/" + kernel_symbol + ".cubin";
    std::ifstream f(path, std::ios::binary);
    if (f) {
      const std::string cubin{std::istreambuf_iterator<char>(f),
                              std::istreambuf_iterator<char>()};
      NVTE_WARN("CUTLASS RTC grouped GEMM: loaded prebuilt cubin ", path, " (",
                cubin.size(), " B) instead of compiling ", kernel_symbol, ".");
      return load_cubin_module(cubin, kernel_symbol);
    }
    NVTE_WARN("CUTLASS RTC grouped GEMM: NVTE_GG_RTC_LOAD_CUBIN_DIR is set but ",
              path, " does not exist; compiling with NVRTC instead.");
  }

  std::string source = concat_strings(
      "#undef NVTE_GG_KERNEL_NAME\n",
      "#define NVTE_GG_KERNEL_NAME ", kernel_symbol, "\n",
      string_code_gemm_rtc_cutlass_grouped_gemm_cu);
  const std::string filename = "cutlass_grouped_gemm_rtc.cu";

  if (auto dir = getenv<std::string>("NVTE_CUTLASS_RTC_DUMP_CUBIN_DIR");
      !dir.empty()) {
    std::ofstream f(dir + "/" + kernel_symbol + ".cu");
    f.write(source.data(), source.size());
  }

  nvrtcProgram program;
  NVTE_CHECK_NVRTC(nvrtcCreateProgram(&program, source.c_str(), filename.c_str(),
                                      0, nullptr, nullptr));

  // For -lineinfo, hgrtc feeds our source string to the frontend on stdin and
  // ignores the name passed to nvrtcCreateProgram, so the DWARF primary file is
  // {dir = process CWD, name = "<stdin>"}. The dump below writes the exact
  // string handed to NVRTC (including the two prepended #undef/#define lines,
  // so line numbers line up) to that path, which is also the input to the
  // offline compile above.
  if (getenv<bool>("NVTE_GG_RTC_LINEINFO", false)) {
    const std::filesystem::path dwarf_src =
        std::filesystem::current_path() / "<stdin>";
    std::ofstream f(dwarf_src, std::ios::binary);
    if (f) {
      f.write(source.data(), source.size());
    }
  }

  std::vector<const char*> opts_ptrs;
  opts_ptrs.reserve(opts.size());
  for (const auto& opt : opts) opts_ptrs.push_back(opt.c_str());

  nvrtcResult compile_result =
      nvrtcCompileProgram(program, opts_ptrs.size(), opts_ptrs.data());
  if (compile_result != NVRTC_SUCCESS) {
    size_t log_size = 0;
    nvrtcGetProgramLogSize(program, &log_size);
    std::string log(log_size, '\0');
    nvrtcGetProgramLog(program, log.data());
    nvrtcDestroyProgram(&program);
    NVTE_ERROR("NVRTC compile failed for ", filename, " (key=", key, "):\n",
               log);
  }

  size_t cubin_size = 0;
  NVTE_CHECK_NVRTC(nvrtcGetCUBINSize(program, &cubin_size));
  std::string cubin(cubin_size, '\0');
  NVTE_CHECK_NVRTC(nvrtcGetCUBIN(program, cubin.data()));
  if (compiled_cubin != nullptr) {
    *compiled_cubin = cubin;
  }

  if (auto dir = getenv<std::string>("NVTE_CUTLASS_RTC_DUMP_CUBIN_DIR");
      !dir.empty()) {
    std::string path = dir + "/" + kernel_symbol + ".cubin";
    std::ofstream f(path, std::ios::binary);
    f.write(cubin.data(), cubin.size());
    NVTE_WARN("Dumped cubin to: ", path);
  }

  const std::string mangled = kernel_symbol;
  nvrtcDestroyProgram(&program);

  return load_cubin_module(cubin, mangled);
}

template <typename Traits>
const CompiledKernel& get_or_compile(int sm_arch, bool trans_a, bool trans_b,
                                     TileConfig const& cfg) {
  using GemmKernel = typename Traits::GemmKernel;
  constexpr int dtype_id =
      std::is_same_v<typename Traits::ElementA, cutlass::half_t> ? 1 : 0;

  const std::vector<std::string> opts =
      make_nvrtc_options(sm_arch, trans_a, trans_b, cfg, dtype_id);

  const std::string kernel_label = make_kernel_label<Traits>(sm_arch, cfg);
  const std::string kernel_symbol = make_kernel_symbol<Traits>(sm_arch, cfg);

  // Build a cache key that includes a digest of the full RTC input (top-level
  // source + every reachable include) and the exact compiler options. This
  // lets TE invalidate its cache whenever any header changes, even though
  // hgrtc's own on-disk cache is disabled with --no-cache.
  const std::string opts_str = [&opts]() {
    std::string s;
    for (const auto& opt : opts) {
      s += opt;
      s += ',';
    }
    return s;
  }();
  const std::string cache_key =
      concat_strings(kernel_label, "|src=", get_rtc_source_digest(),
                     "|opts=", opts_str);

  // The in-process cache holds driver handles, so it is keyed by device as
  // well; the on-disk cubin path stays device-independent (the cubin is
  // selected by sm_arch, not by ordinal).
  const int device = current_device_ordinal();
  const auto mem_key = std::make_pair(device, cache_key);

  std::lock_guard<std::mutex> lk(cache_mutex());
  auto& cache = kernel_cache();

  const bool disable_cache = getenv<bool>("NVTE_GG_DISABLE_RTC_CACHE", false);
  if (!disable_cache) {
    auto it = cache.find(mem_key);
    if (it != cache.end()) return it->second;
  }

  // Try the filesystem cache first (unless disabled). A cubin loaded from
  // disk still needs the same post-processing as a freshly compiled one.
  std::optional<CompiledKernel> ck_opt;
  std::string cubin;
  if (!disable_cache) {
    ck_opt = try_load_cached_cubin(cache_key, kernel_symbol);
  }

  if (!ck_opt) {
    if (getenv<bool>("NVTE_CUTLASS_GROUPED_GEMM_RTC_VERBOSE", false)) {
      NVTE_WARN("CUTLASS RTC compiling new kernel:\n  label=", kernel_label,
                "\n  symbol=", kernel_symbol,
                "\n  src_digest=", get_rtc_source_digest());
    }
    ck_opt = compile_kernel(kernel_label, kernel_symbol, sm_arch,
                            trans_a, trans_b, cfg, dtype_id, opts, &cubin);
  }

  CompiledKernel ck = std::move(*ck_opt);
  // Query smem from the cubin via the driver API — Tile/Stages chosen at
  // runtime can change `sizeof(SharedStorage)`.
  int static_smem = 0;
  NVTE_CALL_CHECK_CUDA_DRIVER(cuFuncGetAttribute, &static_smem,
                              CU_FUNC_ATTRIBUTE_SHARED_SIZE_BYTES,
                              ck.function);
  // Thread count depends on TileShape: on PPU with ClusterShape (64,64,64)
  // and MMA inst 16x16x16, warpM = warpN = 64 (max(InstDim, ClusterDim)),
  // so threads = (tile_m/64) * (tile_n/64) * 32.  The host reference Traits
  // uses (256,128,64) → 256 threads, but the NVRTC kernel can be compiled
  // with a different tile — must use the ACTUAL tile to avoid launching with
  // wrong block dimensions.
  constexpr int kWarpTileM = 64;  // max(InstM=16, ClusterShape_M=64)
  constexpr int kWarpTileN = 64;  // max(InstN=16, ClusterShape_N=64)
  ck.thread_count =
      (cfg.tile_m / kWarpTileM) * (cfg.tile_n / kWarpTileN) * 32;
  ck.tile_m = cfg.tile_m;
  ck.tile_n = cfg.tile_n;
  // SharedStorageSize value from the host reference is computed for the
  // host's tile/stages which may differ from the cubin's. The cubin's
  // actual smem is what the driver reports as "static smem" (since
  // CUTLASS allocates SharedStorage as `extern __shared__` at the kernel
  // entry — but on some toolchains it appears as static). Use the larger
  // of the two as a conservative upper bound — over-allocation is safe;
  // under-allocation is OOB.
  int reference_smem = static_cast<int>(GemmKernel::SharedStorageSize);
  ck.smem_size = std::max(static_smem, reference_smem);
  if (getenv<bool>("NVTE_CUTLASS_GROUPED_GEMM_RTC_VERBOSE", false)) {
    NVTE_WARN("CUTLASS RTC kernel report: threads=", ck.thread_count,
              " (host_ref=", static_cast<int>(GemmKernel::MaxThreadsPerBlock),
              ") static_smem=", static_smem,
              " reference_smem=", reference_smem,
              " chosen_smem=", ck.smem_size, " for ", kernel_symbol);
  }

  if (ck.smem_size >= (48 << 10) && !ck.smem_attr_set) {
    NVTE_CALL_CHECK_CUDA_DRIVER(cuFuncSetAttribute, ck.function,
                                CU_FUNC_ATTRIBUTE_MAX_DYNAMIC_SHARED_SIZE_BYTES,
                                ck.smem_size);
    ck.smem_attr_set = true;
  }

  if (!disable_cache && !cubin.empty()) {
    save_cached_cubin(cache_key, cubin);
  }

  auto [iter, _] = cache.emplace(mem_key, ck);
  return iter->second;
}

