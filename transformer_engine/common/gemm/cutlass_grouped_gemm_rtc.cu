// Resolve CUTLASS 3.x + PPU include directory for NVRTC.
// Follows the same pattern as cuda::include_directory(): env var overrides,
// then build-time baked path (string_path_cutlass3_include), then heuristic
// fallbacks. The baked path is set by CMake's make_string_header() and
// matches CUTLASS3_INCLUDE_DIR at build time — for source builds this is
// 3rdparty/cutlass3/include.
std::string resolve_cutlass_include_dir() {
  namespace fs = std::filesystem;
  auto check = [](const fs::path& p) {
    return !p.empty() && fs::exists(p / "cutlass" / "cutlass.h") &&
           fs::exists(p / "ppu_include.hpp");
  };

  // 1. Explicit env var overrides (highest priority).
  std::vector<std::pair<std::string, fs::path>> search_paths = {
      {"NVTE_CUTLASS3_INCLUDE_DIR", ""},
      {"NVTE_CUTLASS_INCLUDE_DIR", ""},
  };
  for (auto& [env, p] : search_paths) {
    p = getenv<fs::path>(env.c_str());
    if (check(p)) return p.string();
  }

  // 2. Build-time baked path (like string_path_cuda_include for CUDA).
  fs::path baked(string_path_cutlass3_include);
  if (check(baked)) return baked.string();

  // 3. CUTLASS_PATH env var with /include suffix.
  fs::path cutlass_path = getenv<fs::path>("CUTLASS_PATH");
  if (!cutlass_path.empty()) {
    fs::path with_include = cutlass_path / "include";
    if (check(with_include)) return with_include.string();
    if (check(cutlass_path)) return cutlass_path.string();
  }

  // 4. NVTE_HOME / 3rdparty / cutlass3 / include.
  fs::path nvte_home = getenv<fs::path>("NVTE_HOME");
  if (!nvte_home.empty()) {
    fs::path candidate = nvte_home / "3rdparty" / "cutlass3" / "include";
    if (check(candidate)) return candidate.string();
  }

  // 5. Installed-package fallback: headers installed alongside the .so
  //    via CMake install(DIRECTORY ... DESTINATION include/cutlass3).
  {
    Dl_info dl_info;
    if (dladdr(reinterpret_cast<void*>(&resolve_cutlass_include_dir), &dl_info)
        && dl_info.dli_fname) {
      fs::path lib_dir = fs::path(dl_info.dli_fname).parent_path();
      fs::path installed = lib_dir / "include" / "cutlass3";
      if (check(installed)) return installed.string();
    }
  }

  // 6. __FILE__-relative fallback (source tree layout).
  fs::path here(__FILE__);
  fs::path repo_root = here.parent_path()      // gemm
                            .parent_path()    // common
                            .parent_path()    // transformer_engine
                            .parent_path();   // repo root
  fs::path fallback = repo_root / "3rdparty" / "cutlass3" / "include";
  if (check(fallback)) return fallback.string();

  NVTE_ERROR(
      "Could not locate CUTLASS 3.x + PPU include directory. "
      "Searched: NVTE_CUTLASS3_INCLUDE_DIR, baked=",
      string_path_cutlass3_include,
      ", CUTLASS_PATH, NVTE_HOME, dladdr-relative, __FILE__-relative. "
      "Set NVTE_CUTLASS3_INCLUDE_DIR to the directory containing "
      "cutlass/ and ppu_include.hpp.");
}

std::string get_cutlass_include_dir() {
  static std::string cached = resolve_cutlass_include_dir();
  return cached;
}

namespace {

// FNV-1a 64-bit hash, used for the RTC source digest.
static uint64_t fnv1a_64(const void* data, size_t size, uint64_t seed) {
  const uint8_t* p = static_cast<const uint8_t*>(data);
  uint64_t h = seed;
  for (size_t i = 0; i < size; ++i) {
    h ^= static_cast<uint64_t>(p[i]);
    h *= 0x100000001b3ull;
  }
  return h;
}

static std::string digest_to_hex(uint64_t h0, uint64_t h1) {
  std::ostringstream oss;
  oss << std::hex << std::setfill('0')
      << std::setw(16) << h0
      << std::setw(16) << h1;
  return oss.str();
}

// Compute a content hash of everything that can affect the RTC-compiled cubin:
//   - the top-level .cu source string
//   - every header under the resolved CUTLASS/PPU include root
// The result is cached for the lifetime of the process.
std::string compute_rtc_source_digest() {
  namespace fs = std::filesystem;
  std::vector<char> buffer;

  // Top-level RTC source string (generated by CMake from
  // transformer_engine/common/gemm/rtc/cutlass_grouped_gemm.cu).
  const std::string& src = string_code_gemm_rtc_cutlass_grouped_gemm_cu;
  buffer.insert(buffer.end(), src.begin(), src.end());

  // All headers reachable through the include search path.
  const fs::path include_root = get_cutlass_include_dir();
  if (!include_root.empty() && fs::exists(include_root) && fs::is_directory(include_root)) {
    std::vector<fs::path> files;
    for (const auto& entry : fs::recursive_directory_iterator(include_root)) {
      if (!entry.is_regular_file()) continue;
      const auto ext = entry.path().extension();
      if (ext == ".h" || ext == ".hpp" || ext == ".inl" || ext == ".cuh") {
        files.push_back(entry.path());
      }
    }
    std::sort(files.begin(), files.end());

    for (const auto& f : files) {
      // Include the relative path so renames/duplicates are visible.
      const auto rel = fs::relative(f, include_root).string();
      buffer.insert(buffer.end(), rel.begin(), rel.end());

      std::ifstream in(f, std::ios::binary);
      if (!in) continue;
      buffer.insert(buffer.end(),
                    std::istreambuf_iterator<char>(in),
                    std::istreambuf_iterator<char>());
    }
  }

  const uint64_t h0 = fnv1a_64(buffer.data(), buffer.size(), 0xcbf29ce484222325ull);
  const uint64_t h1 = fnv1a_64(buffer.data(), buffer.size(), 0x9e3779b97f4a7c15ull);
  return digest_to_hex(h0, h1);
}

}  // namespace

std::string get_rtc_source_digest() {
  static std::string cached = compute_rtc_source_digest();
  return cached;
}

