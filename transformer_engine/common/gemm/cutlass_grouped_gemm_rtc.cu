template <typename T>
inline T round_up(T m, T n) {
  return (m + n - 1) / n * n;
}

constexpr size_t kCPUWorkSpaceSize = 4 * 1024 * 1024;

namespace {
// Pinned host staging for the H2D parameter transfer. cudaMemcpyAsync from a
// malloc'd (pageable) buffer degenerates to a driver-side staged copy that
// blocks the launching thread and serializes against GPU execution; on
// shallow-K grouped GEMM shapes (kernel ~42 us) that host block dominates the
// per-iteration time. Page-locked memory lets the H2D copy run truly async on
// the copy engine.
//
// The async copy only executes once the stream's prior kernels have
// finished, while the host thread returns immediately and may already be
// staging the NEXT grouped GEMM call. A single shared buffer would therefore
// be overwritten before the queued copy executed, feeding the first kernel
// the second call's (or torn) shapes and pointers. Stage from a ring of
// slots: each slot carries an event recorded after the H2D copy that
// consumed it, and a slot is reused only after that event completed.
// (The kernel itself never dereferences the pinned buffer: it reads shapes
// and pointers from the device workspace copy; host_problem_shapes is only
// consulted host-side during to_underlying_arguments.)
constexpr int kHostWsSlots = 8;
constexpr size_t kHostWsSlotSize = kCPUWorkSpaceSize / kHostWsSlots;

struct HostWsRing {
  char* base = nullptr;  // pinned allocation of kCPUWorkSpaceSize bytes
  cudaEvent_t events[kHostWsSlots] = {};
  bool recorded[kHostWsSlots] = {};
  int next = 0;
  std::mutex mutex;
};

HostWsRing& host_ws_ring(int device) {
  // One ring per device. The slots' reuse events are context-bound (an event
  // can only be recorded on, and synchronized against, streams of the device
  // that created it), so a single process-wide ring breaks the first launch
  // that runs on a second GPU. The pinned buffer is kept per device too so
  // each device's slot lifecycle is self-contained (4 MiB per device).
  static std::mutex rings_mutex;
  static std::map<int, HostWsRing*>* rings = new std::map<int, HostWsRing*>();
  std::lock_guard<std::mutex> lock(rings_mutex);
  if (auto it = rings->find(device); it != rings->end()) return *it->second;

  auto* r = new HostWsRing();
  void* p = nullptr;
  if (cudaHostAlloc(&p, kCPUWorkSpaceSize, cudaHostAllocDefault) ==
      cudaSuccess) {
    r->base = reinterpret_cast<char*>(p);
    for (int i = 0; i < kHostWsSlots; ++i) {
      if (cudaEventCreateWithFlags(&r->events[i],
                                   cudaEventDisableTiming) != cudaSuccess) {
        (void)cudaGetLastError();  // clear the sticky error
        for (int j = 0; j < i; ++j) {
          (void)cudaEventDestroy(r->events[j]);
          r->events[j] = nullptr;
        }
        (void)cudaFreeHost(r->base);
        r->base = nullptr;
        break;
      }
    }
  } else {
    // Fall back to per-call pageable staging if pinning is unavailable
    // (e.g. limited locked-memory quota); correctness is unaffected, only
    // latency.
    (void)cudaGetLastError();  // clear the sticky error
  }
  (*rings)[device] = r;
  return *r;
}
}  // namespace

